/* SR 검증 — 식비는 **여행자의 끼니**만 센다

   왜 —  요율표의 `meal_per_person`은 **여행자 1인 1일 조·중·석식**이다. 그런데 견적서의
   '식사' 묶음에는 그 정의 밖의 줄이 섞여 있고, 어휘 순서상 '식사'가 먼저 걸려 전부
   식비 합에 들어가고 있었다:

     · **인솔진 식사** — 「기사 식사 262,800」·「가이드 식사 262,800」(글로벌 카자흐스탄),
       「기사식사 ¥1,392,000」·「가이드식사 ¥1,392,000」(굿리치 체코).
       그 사람들 밥값은 가이드비·기사비 쪽이지 여행자 식비가 아니다.
     · **끼니가 아닌 것** — 「미케비치 음료」 3,462,500원(다낭, 1잔씩 제공),
       「룸드랍」 210,000원(키움 카자흐스탄, 객실당 라면 2개).

   빼고 나니 11건에서 식비가 **3~16% 내려갔다.** 요율 갱신 후보에서 오키나와가 빠졌다.

   ⚠ **일수는 뺀 줄까지 포함해 센다 — 이걸 놓쳐서 한 번 크게 틀렸다.**
     인솔진 식사도 「× 5회」처럼 며칠짜리 일정인지를 말해 준다. 금액에서 뺐다고 일수
     단서까지 버렸더니, 굿리치 체코에서 남은 줄이 「중식 × 2」뿐이라 일수가 5 → 2로
     떨어졌고 1인 1일 식비가 80,877 → **193,382(+139%)**로 뛰었다.
     **금액과 일수는 다른 문제다.**

   ⚠ **라벨만 본다.** 비고에 「주류/음료 제공」이 적힌 정상 중식 줄이 있다(키움 카자흐스탄) —
     비고까지 보면 그 끼니가 통째로 빠진다.

   ⚠ 「합 ÷ 인원 ÷ 일수」는 그대로 둔다. 줄마다 자기 인원으로 나누는 방식도 재 봤는데,
     15명짜리 부분 끼니를 전원이 먹은 것처럼 세어 웰스 푸꾸옥이 59,670 → 281,233이 됐다.
     **회사가 1인당 하루에 쓴 식비**가 요율이 원하는 값이다.

   실행: node ai-loop/test_sR_meal_scope.js  (프로젝트 루트에서) */
const X = require('../api/_lib/pdf_extract.js');

let pass = 0, fail = 0;
const ok = (name, cond, extra = '') => {
  if (cond) { pass++; console.log('  ✓ ' + name); }
  else { fail++; console.log('  ✗ ' + name + (extra ? '  ← ' + extra : '')); }
};

let ln = 0;
const line = (cells) => {
  const out = { page: 1, y: 700 - ln * 10, idx: ln, cells: [], text: '' };
  let x = 40;
  cells.forEach((s) => { out.cells.push({ s: String(s), x }); x += 40; });
  out.text = out.cells.map((c) => c.s.trim()).filter(Boolean).join(' ');
  ln++;
  return out;
};
const doc = (rows) => { ln = 0; return rows.map((r) => line(r)); };

/* ══ [1] 인솔진 식사를 여행자 식비에 넣지 않는가 ═══════════════════════════ */
console.log('[1] 기사·가이드 식사를 빼는가');
{
  const r = X.readOneBlock(doc([
    ['인 원', '20'],
    ['식사', '1일차 중식', '30,000', '20', '2', '1,200,000'],
    ['식사', '1일차 석식', '40,000', '20', '2', '1,600,000'],
    ['식사', '기사 식사', '20,000', '10', '2', '400,000'],
    ['식사', '가이드 식사', '20,000', '10', '2', '400,000'],
  ]), {}, null);
  const ev = r.evidence.meal;
  ok('여행자 끼니 2줄만 센다', ev && ev.rowIdxs.length === 2, JSON.stringify(ev && ev.rowIdxs));
  ok('합에 인솔진 식사가 안 들어간다',
    String(ev.calc).indexOf((1200000 + 1600000).toLocaleString()) >= 0, ev.calc);
  ok('얼마를 왜 뺐는지 남긴다', /인솔진 식사 800,000원은 뺐습니다/.test(String(ev.note)), String(ev.note));
}

/* ══ [2] 끼니가 아닌 것을 빼는가 ═══════════════════════════════════════════ */
console.log('\n[2] 음료·룸드랍을 빼는가');
{
  const r = X.readOneBlock(doc([
    ['인 원', '20'],
    ['식사', '1일차 중식', '30,000', '20', '2', '1,200,000'],
    ['식사', '1일차 석식', '40,000', '20', '2', '1,600,000'],
    ['식사', '미케비치 음료', '7,000', '20', '1', '140,000'],
    ['식사', '룸드랍', '30,000', '10', '1', '300,000'],
  ]), {}, null);
  const ev = r.evidence.meal;
  ok('여행자 끼니 2줄만 센다', ev && ev.rowIdxs.length === 2, JSON.stringify(ev && ev.rowIdxs));
  ok('얼마를 왜 뺐는지 남긴다', /음료·간식류 440,000원은 뺐습니다/.test(String(ev.note)), String(ev.note));
}
{
  /* ⚠ 비고의 「주류/음료 제공」 때문에 정상 끼니가 빠지면 안 된다 — 라벨만 본다 */
  const r = X.readOneBlock(doc([
    ['인 원', '14'],
    ['식사', '전 일정 중식', '37,500', '14', '4', '2,100,000', '주류/음료 제공'],
    ['식사', '전 일정 석식', '37,500', '14', '4', '2,100,000', '주류/음료 제공'],
  ]), {}, null);
  ok('비고에 「음료」가 있어도 정상 끼니는 센다',
    r.evidence.meal && r.evidence.meal.rowIdxs.length === 2,
    JSON.stringify(r.evidence.meal && r.evidence.meal.rowIdxs));
}

/* ══ [3] 일수는 뺀 줄까지 포함해 센다 ═════════════════════════════════════
   ⚠ 이걸 놓쳐서 굿리치 체코가 80,877 → 193,382(+139%)가 됐다. */
console.log('\n[3] 인솔진 식사를 빼면서 일수 단서까지 버리지 않는가');
{
  const r = X.readOneBlock(doc([
    ['인 원', '158'],
    ['식사', '기사식사', '34,800', '8', '5', '1,392,000'],
    ['식사', '가이드식사', '34,800', '8', '5', '1,392,000'],
    ['식사', '중식', '283,620', '30', '2', '17,017,200'],
    ['식사', '석식', '283,620', '40', '2', '22,689,600'],
  ]), {}, null);
  const ev = r.evidence.meal;
  ok('일수를 5로 센다(인솔진 줄의 횟수도 본다)', ev && ev.dayCount === 5, String(ev && ev.dayCount));
  ok('금액은 여행자 끼니만 더한다',
    String(ev.calc).indexOf((17017200 + 22689600).toLocaleString()) >= 0, ev.calc);
}

/* ══ [4] 전부 빠지면 비운다 ═══════════════════════════════════════════════
   여행자 끼니가 하나도 없는데 인솔진 밥값을 식비라 우기지 않는다. */
console.log('\n[4] 여행자 끼니가 하나도 없으면');
{
  const r = X.readOneBlock(doc([
    ['인 원', '20'],
    ['식사', '기사 식사', '20,000', '10', '2', '400,000'],
    ['식사', '가이드 식사', '20,000', '10', '2', '400,000'],
  ]), {}, null);
  ok('식비를 비운다', r.values.meal == null, String(r.values.meal));
}

/* ══ [5] 「합 ÷ 인원 ÷ 일수」는 그대로 ════════════════════════════════════
   ⚠ 줄마다 자기 인원으로 나누는 방식도 재 봤는데, 15명짜리 부분 끼니를 전원이 먹은
     것처럼 세어 웰스 푸꾸옥이 59,670 → 281,233이 됐다. 요율이 원하는 것은
     **회사가 1인당 하루에 쓴 식비**다. */
console.log('\n[5] 부분 인원 끼니를 전원이 먹은 것으로 세지 않는가');
{
  const r = X.readOneBlock(doc([
    ['인 원', '100'],
    ['식사', '2일차 중식', '150,000', '15', '1', '2,250,000'],
    ['식사', '2일차 석식', '150,000', '15', '1', '2,250,000'],
    ['식사', '3일차 중식', '30,000', '100', '1', '3,000,000'],
  ]), {}, null);
  const v = r.values.meal;
  ok('문서 인원(100)으로 나눈다', v != null && v < 100000, String(v));
  ok('줄마다 나눈 값(=330,000)이 아니다', v !== 330000, String(v));
}

