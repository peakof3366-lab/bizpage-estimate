/* UT 검증: 문서가 밝힌 기간을 더 읽는다 — 「2025. 12. 3 ~ 6」과 해를 넘기는 일정.

   왜 —
   견적서 46건 중 5건이 **출발일이 통째로 비어** 역검증에서 빠져 있었다. 실측으로 열어 보니
   그중 2건은 문서가 기간을 분명히 밝히고 있었다:

       행 사 기 간  2025. 12. 3 ~ 6 (3박 4일)      ← 리더스에셋 어드바이저(푸꾸옥)
       행 사 기 간  2025. 11. 09 ~ 12 (3박 4일)    ← 호남 대학교(북해도)

   오른쪽에 **일자만** 있는 표기(YMD ~ D)를 읽는 규칙이 없었다. ①(YMD~YMD)·②(YMD~MD)는
   있었는데 이 형태만 빠져 있었던 것이다. 출발일은 시즌·리드타임 계수를 통해 금액에
   들어가므로, 비어 있으면 그 건은 대조 자체가 안 된다.

   ⚠ 그리고 ②에 **해를 넘기는 결함**이 있었다. 「2025. 12. 3 ~ 1. 6」에서 뒤쪽 연도를
     앞쪽에서 빌려 와 귀국일이 2025-01-06(출발보다 앞)이 된다. 그러면 날짜로 센 박수가
     음수라 조용히 버려지고, 문서가 밝힌 기간이 통째로 없는 것이 된다.

   여기서 고정하는 것:
   ① YMD ~ D를 읽는다 (문서가 밝힌 것이지 짐작이 아니다).
   ② **②보다 뒤에 와야 한다.** 앞에 두면 「2026. 06. 19 ~ 06. 22」의 '06'을 일자로 읽어
      6일이 귀국일이 된다 — 있던 값을 틀린 값으로 바꾸는 자리다.
   ③ 오른쪽 일자가 왼쪽보다 작으면 **안 받는다.** 다음 달로 넘어간 것인데 몇 월인지
      문서가 말하지 않았다 — 짐작하면 그게 곧 틀린 출발일이 된다.
   ④ 해를 넘기는 범위는 귀국일을 다음 해로 넘긴다 (여행은 떠난 뒤에 돌아온다).
   ⑤ 기존 ①·②·③ 경로가 그대로다.

   실행: node ai-loop/test_uT_trip_date_forms.js  (프로젝트 루트에서) */
const path = require('path');
const ROOT = path.join(__dirname, '..');
const ex = require(path.join(ROOT, 'api', '_lib', 'pdf_extract.js'));

let pass = 0, fail = 0;
const ok = (name, cond, extra = '') => {
  if (cond) { pass++; console.log('  ✓ ' + name); }
  else { fail++; console.log('  ✗ ' + name + (extra ? '  → ' + extra : '')); }
};
const D = (t) => ex.findTripDates([{ text: t }]);

console.log('\n[1] 새 표기 — 오른쪽에 일자만 (YMD ~ D)');
{
  /* 실제 문서 그대로다. ⚠ 「행 사 기 간」은 자간이 벌어져 '기간'으로 안 잡히므로
     낱말 관문을 통과하지 못한다 — 범위 표기만 보는 2차 관문이 잡아야 한다. */
  const a = D('행 사 기 간 2025. 12. 3 ~ 6 (3박 4일)');
  ok('① 리더스에셋(푸꾸옥) 기간을 읽는다',
    a.depart === '2025-12-03' && a.ret === '2025-12-06', a.depart + ' ~ ' + a.ret);
  ok('① 박수·일수도 같은 줄에서 함께 읽는다', a.nights === 3 && a.days === 4,
    a.nights + '박 ' + a.days + '일');

  const b = D('행 사 기 간 2025. 11. 09 ~ 12 (3박 4일)');
  ok('① 호남대(북해도) 기간을 읽는다',
    b.depart === '2025-11-09' && b.ret === '2025-11-12', b.depart + ' ~ ' + b.ret);

  ok('① 낱말 관문을 통과하는 줄에서도 읽는다 (1차에서도 걸린다)',
    D('여행기간 2026. 03. 5 ~ 9').depart === '2026-03-05');
  ok('① 「일」이 붙어도 읽는다',
    D('행 사 기 간 2025년 12월 3일 ~ 6일').depart === '2025-12-03',
    D('행 사 기 간 2025년 12월 3일 ~ 6일').depart);
}

console.log('\n[2] 있던 값을 틀린 값으로 바꾸지 않는가 (순서가 지켜지는가)');
{
  /* ⚠ 이게 이 변경의 진짜 위험이다. 새 규칙이 ②보다 앞서면 '06'을 일자로 읽는다. */
  const a = D('행 2026. 06. 19 ~ 06. 22 (3박 4일)');
  ok('② YMD ~ MD는 예전 그대로 (월.일로 읽는다)',
    a.depart === '2026-06-19' && a.ret === '2026-06-22', a.depart + ' ~ ' + a.ret);
  ok('② 6월 22일이지 6월 6일이 아니다', a.ret === '2026-06-22', a.ret);

  const b = D('여행기간 2026. 06. 19 ~ 2026. 06. 22');
  ok('① YMD ~ YMD도 예전 그대로',
    b.depart === '2026-06-19' && b.ret === '2026-06-22', b.depart + ' ~ ' + b.ret);

  const c = D('출발 2026. 06. 19 (3박 4일)');
  ok('③ 단일 날짜 + 박수도 예전 그대로',
    c.depart === '2026-06-19' && c.nights === 3, c.depart + ' / ' + c.nights);
}

console.log('\n[3] 짐작하지 않는다');
{
  const a = D('행 사 기 간 2025. 12. 30 ~ 2 (3박 4일)');
  ok('③ 오른쪽이 더 작으면 안 받는다 (다음 달인지 문서가 말하지 않았다)',
    a.depart === null && a.ret === null, a.depart + ' ~ ' + a.ret);
  ok('③ 그래도 박수·일수는 읽는다 (읽을 수 있는 것까지 버리지 않는다)',
    a.nights === 3 && a.days === 4);

  const b = D('행 사 기 간 2025. 12. 3 ~ 3');
  ok('③ 같은 날은 안 받는다 (범위가 아니다)', b.depart === null, b.depart);

  /* 단일 날짜는 2차 관문에서 쓰지 않는다 — 문서 아무 데나 있는 날짜가 출발일로 둔갑한다. */
  ok('낱말 없는 줄의 단일 날짜는 여전히 안 받는다',
    D('입금계좌 안내 2026. 06. 19').depart === null,
    String(D('입금계좌 안내 2026. 06. 19').depart));
}

console.log('\n[4] 해를 넘기는 일정');
{
  const a = D('행 사 기 간 2025. 12. 30 ~ 1. 3');
  ok('④ 귀국일이 다음 해로 넘어간다 (출발보다 앞서지 않는다)',
    a.depart === '2025-12-30' && a.ret === '2026-01-03', a.depart + ' ~ ' + a.ret);
  ok('④ 그래서 박수가 제대로 세어진다 (예전엔 음수라 조용히 버려졌다)',
    a.nights === 4 && a.days === 5, a.nights + '박 ' + a.days + '일');

  ok('④ 해를 안 넘기면 예전 그대로 같은 해다',
    D('행 2026. 06. 19 ~ 06. 22').ret === '2026-06-22');
}

console.log('\n결과: ' + pass + ' pass / ' + fail + ' fail');
process.exit(fail ? 1 : 0);
