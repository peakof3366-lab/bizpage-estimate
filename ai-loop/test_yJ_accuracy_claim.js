/* YJ 검증 — 고객 화면이 **재 본 적 없는 정확도를 약속하지 않는가**

   왜 —  랜딩 FAQ 「온라인 견적은 얼마나 정확한가요?」의 답이 이랬다:

       「…분기별 요율 갱신으로 최신 환율·항공 시세를 반영하며,
         **실제 계약 금액과 ±10% 이내로 정확합니다.**」

   세 가지가 사실이 아니었다:
   · 「실제 계약 금액과」 — 운영 DB에 **계약 완료 견적이 0건**이다. 대조해 본 적이 없다.
   · 「±10% 이내로 정확합니다」 — 우리가 실제로 재는 것은 발행 견적서 36건과의 대조이고,
     목표선 ±10% 안에 드는 것은 **15건(42%)**이다.
   · 「분기별 요율 갱신」 — 그런 주기가 없다. 요율 기준월이 옛 날짜인 목적지가 21곳이다(0-u).

   ⚠ 이건 **문구 취향이 아니라 사실 문제**다. 고객이 그 답을 보고 결재를 올린다.
     그리고 하필 「얼마나 정확한가요」라고 **직접 물은 자리**라 가장 크게 읽힌다.

   ⚠ 실측 42%는 **일부러 안 썼다.** 거짓을 걷어내는 것은 결함 수정이지만, 그 숫자를
     광고에 내보낼지는 대표 판단이다(대기열 0-q). 여기서 잠그는 것은
     **「못 잰 것을 잰 것처럼 말하지 않는가」**까지다.

   실행: node ai-loop/test_yJ_accuracy_claim.js  (프로젝트 루트에서) */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
let pass = 0, fail = 0;
const ok = (name, cond, extra = '') => {
  if (cond) { pass++; console.log('  ✓ ' + name); }
  else { fail++; console.log('  ✗ ' + name + (extra ? '  ← ' + extra : '')); }
};

/* 고객이 보는 화면 셋. 주석은 빼고 **렌더되는 글자만** 본다 —
   주석에 옛 문구를 근거로 남겨 두었기 때문에, 안 빼면 그것까지 걸린다. */
/* 🔴 `admin.html`도 넣는다. 거기 같은 글이 **CMS 기본값**으로 또 있었다 —
   담당자가 「기본값으로 되돌리기」를 누르면 그 글이 고객에게 간다.
   index.html만 고치고 끝냈으면 거짓이 되돌아왔을 것이다(결함 생성기 ①). */
const CUSTOMER = ['index.html', 'packages.html', 'estimate-view.html', 'admin.html'];
const visible = (f) => {
  const p = path.join(ROOT, f);
  if (!fs.existsSync(p)) return '';
  return fs.readFileSync(p, 'utf8')
    .replace(/<!--[\s\S]*?-->/g, ' ')      /* HTML 주석 */
    .replace(/\/\*[\s\S]*?\*\//g, ' ');    /* 스크립트 주석 */
};
const SEEN = CUSTOMER.map(visible).join('\n');

/* ══ [1] 잰 적 없는 것을 잰 것처럼 말하지 않는가 ═══════════════════════════ */
console.log('[1] 계약 금액과 대조했다고 말하지 않는가 (계약 완료 0건)');
{
  ok('「실제 계약 금액과 … 정확」이 없다',
    !/실제\s*계약\s*금액과[^.]{0,40}정확/.test(SEEN));
  ok('「±10% 이내로 정확」이 없다', !/±\s*10\s*%\s*이내로\s*정확/.test(SEEN));
  /* ⚠ 숫자만 바꿔 되살아나는 것도 막는다 — 「±5% 이내로 정확」도 같은 거짓이다 */
  ok('숫자를 바꾼 같은 주장도 없다', !/±\s*\d+\s*%\s*이내로\s*정확/.test(SEEN));
}

/* ══ [2] 지키지 못하는 주기를 약속하지 않는가 ═════════════════════════════ */
console.log('\n[2] 요율 갱신 주기');
{
  /* 0-u: 금액은 바뀌었는데 요율 기준월이 옛 날짜인 목적지가 21곳이다 */
  ok('「분기별 요율 갱신」이 없다', !/분기별\s*요율\s*갱신/.test(SEEN));
  ok('다른 주기 약속도 없다', !/(매월|월별|주간|분기)\s*(요율\s*)?갱신/.test(SEEN));
}

/* ══ [3] 그 자리를 비워 두지 않았는가 — 고객이 직접 물은 질문이다 ════════ */
console.log('\n[3] 물음에 답은 하는가');
{
  const idx = visible('index.html');
  ok('「얼마나 정확한가요」 물음이 그대로 있다', /얼마나\s*정확한가요/.test(idx));
  ok('가견적이라 차이가 있을 수 있다고 밝힌다', /가견적/.test(idx) && /차이가 있을 수 있/.test(idx));
  ok('확정 금액은 담당자 견적으로 안내한다고 말한다', /확정 금액은[\s\S]{0,20}담당자/.test(idx));
}

/* ══ [4] 목적지 수가 낡지 않는가 ═════════════════════════════════════════ */
console.log('\n[4] 화면에 적은 목적지 수가 실제와 맞는가');
{
  /* 🔴 예전 글은 「55개 이상」이었는데 실제는 60곳이다. 「이상」이라 거짓은 아니지만,
     이렇게 손으로 적은 숫자는 조용히 낡는다. 실제 수와 대조해 잠근다. */
  const n = require(path.join(ROOT, 'data.js')).length;
  const idx = visible('index.html');
  const m = /목적지\s*(\d+)\s*곳/.exec(idx);
  ok('FAQ가 목적지 수를 적고 있다', !!m, idx.match(/목적지[^<]{0,12}/) || '');
  ok('그 수가 data.js와 같다 (' + n + '곳)', !!m && Number(m[1]) === n, m ? m[1] : '—');
}

/* ══ [5] 관리자가 덮어쓸 수 있는 자리라는 것 ═════════════════════════════ */
console.log('\n[5] CMS로 덮어쓸 수 있는 글이다');
{
  /* ⚠ 이 문단은 `data-cms-key="faq.3.a"`다 — 관리자가 고치면 **파일이 아니라 그 값**이
     고객에게 나간다. 2026-09-02 프로덕션 확인 시 덮어쓴 값은 없었다(파일 글이 그대로 나감).
     이 테스트는 파일을 지킬 뿐, **운영 DB에 거짓이 다시 들어오는 것은 못 막는다.** */
  const idx = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
  ok('그 문단에 cms 키가 있다', /data-cms-key="faq\.3\.a"/.test(idx));
  /* 🔴 CMS **기본값**이 admin.html에 또 있다 — 두 곳이 같은 뜻이어야 한다.
     ⚠ 주석을 빼고 본다 — 그 파일 주석에 **옛 문구를 근거로 인용**해 두었기 때문이다.
       안 빼면 「거짓을 왜 걷어냈는지 적어 둔 글」이 거짓으로 걸린다. */
  const adm = visible('admin.html');
  ok('admin.html의 기본값에도 거짓이 없다',
    !/±\s*\d+\s*%\s*이내로\s*정확/.test(adm) && !/실제\s*계약\s*금액과[^']{0,40}정확/.test(adm));
  ok('admin.html 기본값도 가견적 단서를 담는다', /가견적이라 확정 금액과는 차이/.test(adm));
  const src = fs.readFileSync(__filename, 'utf8');
  ok('이 테스트가 막지 못하는 것을 밝혀 둔다', /운영 DB에 거짓이 다시 들어오는 것은 못 막는다/.test(src));
}

console.log('\n' + '─'.repeat(64));
console.log(`결과: ${pass} pass / ${fail} fail  — YJ 정확도 주장`);
process.exit(fail ? 1 : 0);
