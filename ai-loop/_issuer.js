/* 발행사 — 양식을 가르는 가장 굵은 축이다(같은 회사는 열 구성이 같다).

   🔴 **예전 판은 본문 아무 데나 회사 이름이 있으면 발행사로 찍었다**(YD에서 고침).
   그래서 45건 중 **34건이 「하나투어」**로 나왔는데, 근거를 열어 보니 대부분
   발행처가 아니라 **일정표의 미팅 장소**였다:

       「인천 국제공항 3층 "하나투어" 테이블에서 미팅」   ← 14건이 이 문장 하나 때문
       「인천공항 2청사 하나투어 데스크 미팅」
       「김해공항 국제선 3층 오른쪽 하나투어 안내판 앞」
       「5병은 하나투어 프로모션으로 유로라인 서비스」
       「하나투어 사입석 (인천출발 - 최대 24석 사용 가능)」

   반대로 **진짜 발행처인데 놓친 것**도 있었다 — `Hanatour 견적서_신선혜님(오키나와)`은
   본문이 「(주)하나이엔비티」라 「미상」으로 떨어졌고, `EnBT 세부내역서-제주개발공사`도
   같은 이유로 미상이었다.

   ⚠ **그래서 「어디에 있느냐」를 본다.** 발행처는 ①법인 표기 「(주)○○」이거나
     ②정산 열의 「○○ 수수료/수익」으로 나온다. 미팅 장소·프로모션·사입석 문맥은 뺀다.
   ⚠ **애매하면 미상으로 둔다.** 이 칸은 지금 표시 전용이지만, 틀린 값은 조용히
     축으로 쓰인다(대표 방침: 빈칸보다 틀린 값이 위험하다). 실제로 이 칸을
     「타사 견적서가 섞였나」를 재는 축으로 쓰려다 34건이 거짓인 것을 발견했다.
   ⚠ **근거를 함께 남긴다**(`issuerWhy`). 판정만 남기면 다음 사람이 또 못 믿는다. */

const ISSUERS = [
  /* 우리 법인이 먼저다 — 「(주)하나이엔비티」에는 「하나」가 들어 있어
     하나투어를 먼저 보면 우리 문서가 전부 하나투어로 떨어진다. */
  { key: 'EnBT', re: /\(주\)\s*하나이엔비티|하나이엔비티|EnBT|ENBT|이앤비티|이엔비티/gi },
  { key: '좋은친구', re: /\(주\)\s*좋은\s*친구|좋은\s*친구/g },
  { key: '하나투어', re: /하나투어|HANATOUR|Hanatour|\bHNT\b/gi },
  { key: '모두투어', re: /모두투어/g },
  { key: '노랑풍선', re: /노랑풍선/g },
];

/* 🔴 **가장 센 근거는 「발신」 칸이다.** 견적서 양식이 「수신 ○○ 귀하 … 발신 ○○」로
   적고 있다(실측: 하나투어·하나이엔비티·좋은친구 세 회사 모두 이 칸을 쓴다).
   이게 있으면 다른 근거를 볼 필요가 없다 — 문서가 스스로 밝힌 것이다.
   ⚠ 「발신」 뒤 30자 안에서만 찾는다. 넓히면 본문이 딸려 들어와 다시 오탐이 된다. */
const SENDER_RE = /발\s*신\s*[:：]?\s*([^\n]{0,30})/g;

function issuerFromSender(t) {
  let m;
  const re = new RegExp(SENDER_RE.source, 'g');
  while ((m = re.exec(t))) {
    const seg = m[1];
    for (const it of ISSUERS) {
      if (new RegExp(it.re.source, it.re.flags.replace('g', '')).test(seg)) {
        return { key: it.key, why: '발신 칸 —「' + m[0].replace(/\s+/g, ' ').trim() + '」' };
      }
    }
  }
  return null;
}

/* 🔴 **「발신」 칸 하나만 근거로 쓴다.** 넓히려다 두 번 틀렸고, 둘 다 방향이 반대였다:

     · 「수 신: 하나투어 이선애 선임님 귀하」(신한 발리) — 하나투어는 **받는 쪽**이다.
       「귀하」를 근거에 넣었더니 랜드사가 하나투어에 보낸 문서가 하나투어 발행이 됐다.
     · 「HNT 수익 · 권장수익」 20건 — 이건 **하나투어 원가 열**이지 발행처 표시가 아니다.
       그리고 같은 신호를 `basis`(원가 시트인가)가 이미 세고 있다. 여기서 또 세면
       한 신호를 두 칸에 적는 것이라, 나중에 둘이 어긋나도 아무도 모른다(결함 생성기 ①).

   ⚠ 그래서 **못 정하면 미상으로 둔다.** 45건 중 13건만 확정되지만, 이 칸을 축으로
     쓰려던 사람(=나)이 34건짜리 거짓 「하나투어」에 속을 뻔한 것이 이 규칙의 이유다.
     대표 방침 그대로다 — **빈칸보다 틀린 값이 위험하다.**
   ⚠ 나머지를 알고 싶으면 `issuerWhy`와 `basis`를 함께 본다. 「원가 시트 + 미상」은
     사실상 홀세일러 양식이라는 뜻이고, 그건 `basis`가 이미 말하고 있다.

   @returns {{key: string, why: string}}  못 찾으면 key = '미상' */
function issuerOf(text) {
  const t = String(text || '');
  const bySender = issuerFromSender(t);
  if (bySender) return bySender;
  return { key: '미상', why: '문서에 「발신」 칸이 없거나 아는 회사가 아니다 — 짐작하지 않는다' };
}

module.exports = { issuerOf, ISSUERS, SENDER_RE };
