/* ═══════════════════════════════════════════════════════════════════════════
   블랙다운 줄 → 우리 요율 9칸, 그리고 **그 칸의 「무엇당」** (ZG)
   ───────────────────────────────────────────────────────────────────────────
   ⚠ 이 표는 원래 `build_bd_db.js` 안에만 있었다. `audit_bd_rate_gap.js`가 같은
     분류를 써야 해서 떼어냈다 — 복사해 두면 한쪽만 고쳐지고 두 도구가 **다른 칸을**
     세게 된다(결함 생성기 ①. 이 저장소가 여섯 번 당한 유형이다).

   🔴 **이 파일의 핵심은 분류표가 아니라 `DENOM`이다.**

   블랙다운의 단가와 우리 요율표의 단가는 **이름이 같아도 「무엇당」이 다르다.**
   그걸 안 맞추고 숫자만 견주면 그 자리에서 틀린 배수가 나온다. 실측 전례:
     · 호텔 「단가」가 실 수를 인원으로 읽어 **3.7배**가 됐다 (YL)
     · 식비를 1인 1식으로 보고 7번 곱해 **3.45배**가 됐다 (RO)

   그래서 **엔진이 실제로 곱하는 수**를 분모로 삼는다. `script.js` 실측:

       hotel_per_room    × rooms × nights      → 1실 1박
       meal_per_person   × 인원  × 일수        → 1인 1일   (1인 1식이 아니다 — RO)
       vehicle_small/large × 대수 × 일수       → 1대 1일
       guide_fee         × 명수 × 일수         → 1명 1일   (명수 = 차량 대수)
       sightseeing_fee   × 인원                → 1인 전 일정 묶음 (4~5일 기준, PC)

   🔴 **분모를 「문서가 말하는 수」가 아니라 「엔진이 쓰는 수」로 잡는 이유.**
     우리가 재려는 것은 「랜드사가 몇 실을 잡았나」가 아니라 **「엔진의 오차가 어느 칸에서
     나오나」**다. 엔진 분모를 고정해 두면
         (실측 합계 ÷ 엔진 분모) vs 요율표 값
     의 차이가 **그 칸이 총액에 낸 오차와 정확히 같은 뜻**이 된다. 문서 분모로 나누면
     「실 수가 달랐다」와 「단가가 달랐다」가 섞여 처방을 못 만든다.

   ⚠ 항공·유류는 분모를 두지 않았다. 블랙다운은 **지상비 원가 시트**라 항공이 거의
     없다(실측: 닫힌 43건에서 항공으로 분류된 줄이 4개뿐). 있는 것도 국내수송·차터라
     우리 `airfare`와 뜻이 다르다 → 세되 대조하지 않는다.
   ⚠ 부대·미분류도 대조하지 않는다. **요율표에 그 칸이 없기 때문**이다. 이건 결함이
     아니라 발견이다 — 견적서 PDF 쪽에서 「돈의 12.4%가 우리 9칸 밖」을 알아낸 것과
     같은 자리라, 억지로 넣지 않고 **금액과 비중을 따로 보고한다.**
   ═══════════════════════════════════════════════════════════════════════════ */
const { vehicleCapacity, vehicleFieldFor, roomsDouble } = require('./_engine_consts');

/* ── 줄 이름 → 우리 9칸 ──────────────────────────────────────────────────────
   ⚠ **모르는 것은 「미분류」로 두고 반드시 센다.** 억지로 가장 가까운 칸에 넣으면
     그 칸의 실측 중앙값이 조용히 오염된다. 견적서 PDF 쪽에서 「돈의 12.4%가 우리 9칸
     어디에도 안 들어간다」를 알아낸 것이 바로 미분류를 세었기 때문이다. */
const CELL_RULES = [
  ['항공', /항공|AIR\b|항공권|유류|TAX|택스/i],
  ['호텔', /호텔|숙박|객실|룸|ROOM|HOTEL|온천장|리조트|엑스트라|싱글|SGL|TWN|TRP/i],
  ['식사', /식사|중식|석식|조식|만찬|식대|MEAL|뷔페|BF|런치|디너|식비/i],
  ['차량', /차량|버스|BUS|전용차|송영|주차|기사|COACH|밴|VAN|스프린터/i],
  ['가이드', /가이드|GUIDE|인솔|TC\b|T\/C|쓰루|로컬가이드|현지인가이드/i],
  ['관광', /관광|입장|투어|TOUR|체험|마사지|쇼\b|유람|승선|케이블|스파|골프|라운딩|그린피/i],
  ['부대', /핸들링|HANDLING|팁|TIP|인두세|서비스|봉사료|보험|물|생수|현수막|기념품|챠지|CHARGE/i],
];

/* ⚠ **분류(구분 칸)를 줄 이름보다 먼저 본다.** 줄 이름은 「헤난」「점보크랩」처럼
   업체 이름이라 규칙에 안 걸린다 — 분류는 블록 왼쪽 칸에 있다. */
function cellOf(label, group) {
  for (const src of [group, label]) {
    const t = String(src || '');
    if (!t) continue;
    for (const [name, re] of CELL_RULES) if (re.test(t)) return name;
  }
  return '미분류';
}

/* ── 칸 → [요율 필드, 엔진 분모] ────────────────────────────────────────────
   분모 함수는 `{pax, days, nights}`를 받아 **엔진이 그 칸에 곱하는 수**를 돌려준다.
   ⚠ 분모가 0이거나 셀 수 없으면 **null을 돌려준다** — 그 문서의 그 칸은 대조에서
     빠지고, 빠진 개수는 화면이 밝힌다. 0으로 나눠 Infinity를 만들면 중앙값이
     통째로 망가지는데 그게 눈에는 안 띈다(결함 생성기 ②). */
const CELL_TO_RATE = {
  호텔: {
    field: () => 'hotel_per_room',
    denom: ({ pax, nights }) => (pax > 0 && nights > 0 ? roomsDouble(pax) * nights : null),
    unit: '1실 1박',
  },
  식사: {
    field: () => 'meal_per_person',
    denom: ({ pax, days }) => (pax > 0 && days > 0 ? pax * days : null),
    unit: '1인 1일',
  },
  차량: {
    /* ⚠ 인원이 차량 칸을 가른다 — 25명 이하는 `vehicle_small`이다(_engine_consts).
       인원과 무관하게 `vehicle_large`에 견주다가 25명 이하 견적이 **고객이 보지도
       않는 칸**과 대조된 전례가 있다(VL). */
    field: ({ pax }) => vehicleFieldFor(pax),
    denom: ({ pax, days }) => {
      if (!(pax > 0) || !(days > 0)) return null;
      const cap = vehicleCapacity();
      const large = vehicleFieldFor(pax) === 'vehicle_large';
      return Math.max(1, Math.ceil(pax / (large ? cap.large : cap.small))) * days;
    },
    unit: '1대 1일',
  },
  가이드: {
    /* 엔진: `guideCount = vehicleCount` — 가이드는 버스당 1명이다(P13). */
    field: () => 'guide_fee',
    denom: ({ pax, days }) => CELL_TO_RATE.차량.denom({ pax, days }),
    unit: '1명 1일',
  },
  관광: {
    /* ⚠ 일수를 곱하지 않는다 — `sightseeing_fee`는 **전 일정 묶음**이다(PC).
       엔진은 여기에 `sightDuration.factor`를 따로 곱하는데, 그 계수는 4~5일에서 1.0이다.
       그래서 4~5일 문서는 그대로 견줄 수 있고, 그 밖은 계수만큼 흔들린다 → 표시한다. */
    field: () => 'sightseeing_fee',
    denom: ({ pax }) => (pax > 0 ? pax : null),
    unit: '1인 전일정',
  },
};

/* 대조하지 않는 칸과 그 이유 — **조용히 빠지지 않게** 이름을 남긴다. */
const NOT_COMPARED = {
  항공: '블랙다운은 지상비 원가 시트다 — 항공 줄은 국내수송·차터라 `airfare`와 뜻이 다르다',
  부대: '요율표에 이 칸이 없다 (핸들링·팁·인두세·보험) — 엔진이 낼 수 없는 돈이다',
  미분류: '아직 이름을 못 붙인 돈 — 억지로 칸에 넣지 않는다',
};

module.exports = { CELL_RULES, cellOf, CELL_TO_RATE, NOT_COMPARED };
