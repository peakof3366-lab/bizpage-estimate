/* SP 검증 — 견적서가 적어 둔 **1인당 금액**을 읽는다

   왜 —  1인당은 이 추출기의 **채점표**다. 고객에게 나간 견적서의 1인당은 맞는 숫자이므로,
   우리 엔진이 같은 조건으로 낸 금액과 견주면 오차를 잴 수 있다(`backtest_quotes.js`).
   1인당을 못 읽으면 그 견적서는 **채점에 아예 쓰이지 못한다.**

   실측: 코퍼스 46건 중 대조 가능이 **16건뿐**이었고, 제외 사유 1위가 「1인당 금액을 못
   읽음」 **12건**이었다. 문서는 적어 두고 있는데 패턴이 「1인당」·「인당 요금」만 봤다:
     「성인 (1인) ₩3,020,000 x 10명」  ← '1인'과 '당'이 떨어져 있다
     「1 인 금액 1,479,125」            ← '금액'은 패턴에 없었다
     「● 인당 : ₩3,750,000」           ← '요금'이 없다
   넓히니 대조 가능 16 → **21건**이 됐다.

   ⚠ **여기서 환율 환산을 하면 안 된다.** `wonNumbers`로 바꿔 봤다가 크게 당했다 —
     엔화 견적서의 「¥289,800」이 원화로 환산돼(×9.5 = 2,753,100) 1인당 후보에 들어갔고,
     `Math.max`가 그것을 골라 삿포로 1인당이 1,746,000 → **2,753,100**이 됐다.
     역검증 중앙값이 -9.6% → -13.0%, 최악이 **-63.4%**가 됐다.
     1인당은 원화로 적히는 것이 압도적이라, 외화 1인당은 **읽지 않고 비운다.**

   실행: node ai-loop/test_sP_per_person.js  (프로젝트 루트에서) */
const X = require('../api/_lib/pdf_extract.js');

let pass = 0, fail = 0;
const ok = (name, cond, extra = '') => {
  if (cond) { pass++; console.log('  ✓ ' + name); }
  else { fail++; console.log('  ✗ ' + name + (extra ? '  ← ' + extra : '')); }
};

let ln = 0;
const line = (cells) => {
  const out = { page: 1, y: 700 - ln * 10, idx: ln, cells: [], text: '' };
  let x = 40;
  cells.forEach((s) => { out.cells.push({ s: String(s), x }); x += 40; });
  out.text = out.cells.map((c) => c.s.trim()).filter(Boolean).join(' ');
  ln++;
  return out;
};
const doc = (rows) => { ln = 0; return rows.map((r) => line(r)); };
/* 1인당은 그 자체로 읽혀야 한다 — 표가 있든 없든 */
const pp = (rows) => X.readOneBlock(doc(rows), {}, null).perPerson;

/* ══ [1] 못 읽던 네 가지 표기 ═══════════════════════════════════════════════ */
console.log('[1] 문서가 적어 둔 1인당을 읽는가');
{
  ok('「성인 (1인) ₩3,020,000 x 10명 ₩ 30,200,000」',
    pp([['인 원', '10'], ['성인 (1인)', '₩3,020,000', 'x', '10명', '₩', '30,200,000']]) === 3020000,
    String(pp([['인 원', '10'], ['성인 (1인)', '₩3,020,000', 'x', '10명', '₩', '30,200,000']])));
  ok('「1 인 금액 1,479,125」',
    pp([['인 원', '16'], ['총 금액', '23,666,000'], ['1 인 금액', '1,479,125']]) === 1479125);
  ok('「● 인당 : ₩3,750,000」',
    pp([['인 원', '5'], ['총 금액', '18,750,000'], ['● 인당 : ₩3,750,000']]) === 3750000);
  ok('「일인당 1,944,000」',
    pp([['인 원', '10'], ['총 금액', '19,440,000'], ['일인당', '1,944,000']]) === 1944000);
  /* 예전부터 되던 것들이 그대로인지 */
  ok('「1인당」은 그대로 읽는다',
    pp([['인 원', '10'], ['총 금액', '12,000,000'], ['1인당', '1,200,000']]) === 1200000);
  ok('「판매가」도 그대로 읽는다',
    pp([['인 원', '10'], ['총 금액', '12,513,500'], ['판매가', '1,251,350']]) === 1251350);
}

/* ══ [2] 외화 1인당은 읽지 않는다 ═══════════════════════════════════════════
   ⚠ 읽으려다 엔화 숫자를 원화로 환산해 1인당이 1.6배가 된 전례가 있다.
     틀린 채점표는 없는 것보다 나쁘다 — 오차를 재는 자 자체가 망가진다. */
console.log('\n[2] 엔화 숫자를 1인당으로 환산해 넣지 않는가');
{
  const lines = doc([
    ['인 원', '33'],
    ['호텔', '도야 만세각', '¥', '14,500', '1', '33', '¥', '478,500'],
    ['1인(엔화)', '¥', '77,485'],
    ['판매가', '1,746,000'],
  ]);
  const r = X.readOneBlock(lines, { JPY: 9.5 }, null);
  ok('원화로 적힌 판매가를 쓴다', r.perPerson === 1746000, String(r.perPerson));
  ok('엔화 1인당을 환산해 쓰지 않는다', r.perPerson !== Math.round(77485 * 9.5), String(r.perPerson));
}
{
  /* 엔화 단가 줄이 있는 문서에서 1인당이 그 줄에 오염되지 않는지 */
  const r = X.readOneBlock(doc([
    ['인 원', '135'],
    ['호텔', '삿포로', '¥', '289,800', '1', '135', '¥', '39,123,000'],
    ['1 인 금액', '1,746,000'],
  ]), { JPY: 9.5 }, null);
  ok('¥289,800 × 9.5(=2,753,100)가 1인당이 되지 않는다',
    r.perPerson === 1746000, String(r.perPerson));
}

/* ══ [3] 1인당 × 인원이 총액과 딴판이면 버린다 (예전 규칙 유지) ═══════════ */
console.log('\n[3] 잘못 집은 1인당을 그대로 쓰지 않는가');
{
  const r = X.readOneBlock(doc([
    ['인 원', '10'],
    ['총 금액', '30,200,000'],
    ['1인당', '500,000'],
  ]), {}, null);
  ok('1인당 × 인원이 총액과 크게 다르면 비운다', r.perPerson == null, String(r.perPerson));
}
{
  const r = X.readOneBlock(doc([
    ['인 원', '10'],
    ['총 금액', '30,200,000'],
    ['1인당', '3,020,000'],
  ]), {}, null);
  ok('맞아떨어지면 그대로 쓴다', r.perPerson === 3020000, String(r.perPerson));
}

/* ══ [4] 요약 줄이 단가 줄로 잡히지 않는 것은 그대로 (SH) ═════════════════ */
console.log('\n[4] SH에서 고친 것이 풀리지 않았는가');
{
  const rows = X.findUnitRows(doc([
    ['성인 (1인)', '₩3,020,000', 'x', '10명', '₩', '30,200,000'],
    ['하버그랜드구룡', '275,500', '6', '4', '6,612,000'],
  ]), {});
  ok('「성인 (1인)」 줄은 여전히 단가 줄이 아니다', !rows.some((r) => r.unit === 3020000));
  ok('진짜 항목 줄은 그대로 남는다', rows.some((r) => r.unit === 275500));
}

/* ⚠ 이 요약 줄의 형식은 run_all_tests.js가 정규식으로 읽는다(「결과: N pass / M fail」). */
console.log('\n결과: ' + pass + ' pass / ' + fail + ' fail');
process.exit(fail === 0 ? 0 : 1);
