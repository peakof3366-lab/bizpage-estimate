/* 서로 다른 증거 여섯 갈래. **갈래 수를 센다** — 같은 갈래가 열 번 나와도 하나다. */
const EVIDENCE = [
  ['골프', /골프/g],
  ['그린피', /그린\s*피|그린피/g],
  ['캐디', /캐디/g],
  ['라운딩', /라운딩|라운드\s*비/g],
  /* 「18홀」·「9 홀」 — 골프장 이름 뒤에 거의 언제나 붙는다 */
  ['n홀', /\d+\s*홀/g],
  ['골프장', /골프장|G\.C\b|GOLF/g],
];

/* 골프 일정으로 보려면 갈래가 몇 개 필요한가.
   ⚠ 1로 낮추면 지나가는 말 3건이 들어오고, 3으로 올리면 고은회 제주도(그린피·캐디
     두 갈래뿐인 진짜 골프 일정)를 놓친다. 실측으로 고른 값이다. */
const MIN_KINDS = 2;

/* @param {string} text  견적서 본문 (pdf-parse가 읽은 그대로)
   @returns {{isGolfTrip: boolean, kinds: number, evidence: string[]}}
     evidence — 어느 갈래가 몇 번 나왔는지. **판정만 남기지 않는다**:
     다음에 「이 문서가 왜 골프로 세어졌나」를 물을 때 답할 수 있어야 한다. */
function golfScope(text) {
  const t = String(text || '');
  const evidence = [];
  for (const [name, re] of EVIDENCE) {
    const n = (t.match(re) || []).length;
    if (n) evidence.push(name + '×' + n);
  }
  return { isGolfTrip: evidence.length >= MIN_KINDS, kinds: evidence.length, evidence };
}

module.exports = { golfScope, EVIDENCE, MIN_KINDS };
