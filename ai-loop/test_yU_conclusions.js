/* ═══════════════════════════════════════════════════════════════════════════
   YU — **서 있는 결론이 언제 낡는지 아무도 안 알려 준다**
   ───────────────────────────────────────────────────────────────────────────
   이 저장소에는 측정으로 내린 결론이 여럿 서 있다 — 「요율 천장」·「골프 축은 우연」·
   「마진이 얇지 않다」. 전부 **그때의 표본에서** 내렸는데, 대표 방침은 **견적서가
   계속 는다**이다. 표본이 늘면 뒤집힐 수 있는데 **아무것도 그 사실을 말하지 않는다.**

   메모리에 「`28/36`만 옮겨 적지 말 것」·「폭 12.0%만 옮겨 적지 말 것」이라는 경고가
   여러 번 적혀 있다 — **이미 일어나고 있다**는 뜻이다. 숫자만 남고 근거 표본이 사라진다.

   🔴 잠그는 것 여섯:
     ① 결론마다 **어느 표본 몇 건에서** 내렸는지가 적혀 있다
     ② 표본이 늘면 **다시 재라고 말한다**(문턱 20%)
     ③ 🔴 **표본이 작아 잘 뒤집히는 결론은 더 일찍**(10%) 말한다
     ④ **표본 종류를 가른다** — 전체 문서가 늘어도 역검증 표본은 안 늘 수 있다.
        「45건이 됐으니 전부 다시 재라」는 틀린 말이다
     ⑤ 결론의 **근거를 여기 옮겨 적지 않는다** — 커밋에 있다(두 벌이면 어긋난다)
     ⑥ 「다시 잴 것 없음」을 **「결론이 맞다」로 말하지 않는다**

   실행: node ai-loop/test_yU_conclusions.js
   ═══════════════════════════════════════════════════════════════════════════ */
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const C = require('./audit_conclusions.js');

let pass = 0, fail = 0;
const ok = (name, cond, extra = '') => {
  if (cond) { pass++; console.log('  ✓ ' + name); }
  else { fail++; console.log('  ✗ ' + name + (extra ? '  → ' + extra : '')); }
};
const done = () => {
  console.log('\n' + '─'.repeat(64));
  console.log(`결과: ${pass} pass / ${fail} fail  — YU 결론이 언제 낡는가`);
  process.exit(fail ? 1 : 0);
};

console.log('\n[1] ① 결론마다 표본과 다시 재는 법이 적혀 있다');
{
  ok('① 결론이 여럿 등록돼 있다', C.결론들.length >= 5, String(C.결론들.length));
  let 빠진것 = [];
  for (const c of C.결론들) {
    if (!c.id || !c.한줄 || !c.커밋 || !c.표본 || !c.그때 || !c.다시) 빠진것.push(c.id || '(이름없음)');
    if (!C.표본종류[c.표본]) 빠진것.push(c.id + ': 모르는 표본 종류 ' + c.표본);
  }
  ok('🔴 ① 빠진 칸이 없다(표본·건수·다시 재는 명령)', 빠진것.length === 0, 빠진것.join(', '));

  /* 다시 재는 명령이 **실제로 있는 파일**이어야 한다 — 없는 명령을 적어 두면
     그 결론은 영영 다시 못 잰다(결함 생성기 ③). */
  const 없는도구 = C.결론들
    .map((c) => (c.다시.match(/ai-loop\/[\w.]+\.js/) || [''])[0])
    .filter((f) => f && !fs.existsSync(path.join(ROOT, f)));
  ok('🔴 ① 다시 재는 도구가 실제로 있다', 없는도구.length === 0, 없는도구.join(', '));

  /* 커밋 이름이 이 저장소 방식(YF·VL 같은 두 글자)인가 — 근거를 찾아갈 수 있어야 한다 */
  ok('① 커밋 이름이 적혀 있다', C.결론들.every((c) => /^[A-Z]{1,2}$/.test(c.커밋)),
    C.결론들.map((c) => c.커밋).join(','));
}

console.log('\n[2] 🔴 ②③ 표본이 늘면 다시 재라고 말한다');
{
  const 보통 = { 그때: 36, 표본: '역검증' };
  ok('② 그대로면 유효하다', C.판정(보통, 36).상태 === '유효', C.판정(보통, 36).상태);
  ok('② 10% 늘어도 아직 유효하다(보통 결론)', C.판정(보통, 40).상태 === '유효',
    C.판정(보통, 40).상태 + ' (' + Math.round((40 - 36) / 36 * 100) + '%)');
  ok('🔴 ② 20% 늘면 다시 재라고 한다', C.판정(보통, 44).상태 === '다시재기',
    C.판정(보통, 44).상태 + ' (' + Math.round((44 - 36) / 36 * 100) + '%)');

  const 민감 = { 그때: 8, 표본: '골프', 민감: true };
  ok('🔴 ③ 잘 뒤집히는 결론은 10%에서 이미 말한다', C.판정(민감, 9).상태 === '다시재기',
    C.판정(민감, 9).상태 + ' (' + Math.round((9 - 8) / 8 * 100) + '%)');
  ok('③ 그대로면 민감해도 유효하다', C.판정(민감, 8).상태 === '유효');
  /* 같은 증가율이라도 민감/보통이 갈려야 ③이 의미가 있다 */
  ok('🔴 ③ 같은 +12.5%에서 보통은 유효, 민감은 다시재기',
    C.판정({ 그때: 8, 표본: '역검증' }, 9).상태 === '유효' && C.판정(민감, 9).상태 === '다시재기');

  ok('② 표본이 줄면 그렇다고 말한다(조용히 유효로 두지 않는다)',
    C.판정(보통, 30).상태 === '줄었다', C.판정(보통, 30).상태);
  ok('② 셀 수 없으면 「모름」이다', C.판정(보통, null).상태 === '모름');
}

console.log('\n[3] 🔴 ④ 표본 종류를 가른다');
{
  const 종류 = Object.keys(C.표본종류);
  ok('④ 종류가 여럿이다', 종류.length >= 3, 종류.join(', '));
  ok('④ 역검증과 전체를 따로 센다', 종류.includes('역검증') && 종류.includes('전체'));

  /* 🔴 세는 함수가 실제로 다른 값을 내야 한다 — 같으면 가른 의미가 없다.
     정답지가 없는 문서는 역검증에 못 들어간다. */
  const 가짜 = [
    { perPerson: 100, dates: { departDate: '2026-01-01' }, dest: { key: '도쿄' }, golf: { isGolfTrip: true } },
    { perPerson: 100, dates: { departDate: '2026-01-01' }, dest: { key: '도쿄' } },
    { perPerson: null, dates: {}, dest: null },                 /* 정답지 없음 */
    { perPerson: 100, dates: {}, dest: { key: '도쿄' } },        /* 출발일 없음 */
  ];
  ok('④ 전체는 4건', C.표본종류.전체.세기(가짜) === 4, String(C.표본종류.전체.세기(가짜)));
  ok('④ 정답지는 3건', C.표본종류.정답지.세기(가짜) === 3, String(C.표본종류.정답지.세기(가짜)));
  ok('🔴 ④ 역검증은 2건 — 출발일 없는 것은 빠진다', C.표본종류.역검증.세기(가짜) === 2,
    String(C.표본종류.역검증.세기(가짜)));
  ok('④ 골프는 1건', C.표본종류.골프.세기(가짜) === 1, String(C.표본종류.골프.세기(가짜)));
}

console.log('\n[4] 🔴 ⑤⑥ 근거를 옮겨 적지 않고, 「없음」을 「맞다」로 말하지 않는다');
{
  const src = fs.readFileSync(path.join(ROOT, 'ai-loop', 'audit_conclusions.js'), 'utf8');
  /* ⑤ 한 줄 요약은 짧아야 한다 — 길면 그게 곧 근거를 옮겨 적은 것이다 */
  const 긴것 = C.결론들.filter((c) => c.한줄.length > 120).map((c) => c.id + '(' + c.한줄.length + '자)');
  ok('🔴 ⑤ 한 줄 요약이 길지 않다(근거를 옮겨 적지 않았다)', 긴것.length === 0, 긴것.join(', '));
  ok('⑤ 근거는 커밋에 있다고 화면이 말한다', /근거와 과정은 \*\*커밋 메시지\*\*에 있습니다/.test(src));

  ok('🔴 ⑥ 「다시 잴 것 없음」을 「결론이 맞다」로 말하지 않는다',
    /「결론이 맞다」는 뜻이 아니라/.test(src));
  /* 새 결론을 안 넣으면 이 장치가 조용히 비어 간다 — 그 사실도 말해야 한다 */
  ok('⑥ 새 결론을 등록하라고 말한다', /`결론들`에 한 줄 넣으십시오/.test(src));
}

done();
