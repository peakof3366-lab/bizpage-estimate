/* SQ 검증 — 요일이 끼거나 연도 뒤가 공백인 기간 표기도 읽는다

   왜 —  출발일이 없으면 역검증에서 **시즌 계수를 맞출 수 없어** 그 견적서는 채점에서
   통째로 빠진다. 실측: 대조 가능 21건 중 「출발일 불명」이 6건이었고, 파 보니 문서는
   기간을 **적어 두고 있는데** 두 가지 모양에서 패턴이 막혔다:

     ① **요일이 날짜와 물결표 사이에 낀다** — 「행사기간 2026. 4. 7 (화) ~ 4. 11 (토)」
        날짜와 `~` 사이에 공백만 허용해서 `(화)`에 걸렸다.
     ② **연도와 월 사이가 공백** — 「행사기간 2026 06. 09 ~ 06. 13」
        구분자(`.`·`-`·`/`)를 요구해서 이 줄을 통째로 놓쳤다.

   넓히니 대조 가능 21 → **25건**, 「출발일 불명」 6 → 2건이 됐다.

   ⚠ 괄호 안은 **3글자까지만** 건너뛴다 — 요일·「확정」 같은 짧은 표시만 넘으려는 것이지
     아무 괄호나 넘으라는 뜻이 아니다. 긴 괄호를 넘기면 문서 여기저기의 날짜 둘이
     엉뚱하게 이어진다.
   ⚠ SA가 정한 것은 그대로 유지한다 — 단일 날짜는 2차 훑기에서 쓰지 않고(아무 날짜나
     출발일로 둔갑한다), 제목의 박수와 날짜가 어긋나면 **날짜 쪽**을 쓰되
     `nightsConflict`로 흔적을 남긴다(「3박 5일」은 그 자체로 모순이다).

   실행: node ai-loop/test_sQ_trip_dates2.js  (프로젝트 루트에서) */
const X = require('../api/_lib/pdf_extract.js');

let pass = 0, fail = 0;
const ok = (name, cond, extra = '') => {
  if (cond) { pass++; console.log('  ✓ ' + name); }
  else { fail++; console.log('  ✗ ' + name + (extra ? '  ← ' + extra : '')); }
};

let ln = 0;
const line = (text) => ({ page: 1, y: 700 - (ln++) * 10, idx: ln, cells: [{ s: text, x: 40 }], text });
const doc = (rows) => { ln = 0; return rows.map(line); };
const trip = (rows) => X.findTripDates(doc(rows));

/* ══ [1] 요일이 끼어 있어도 읽는가 ═══════════════════════════════════════ */
console.log('[1] 「2026. 4. 7 (화) ~ 4. 11 (토)」');
{
  const t = trip(['행 사 기 간 2026. 4. 7 (화) ~ 4. 11 (토) / 3박 5일']);
  ok('출발일을 읽는다', t.depart === '2026-04-07', String(t.depart));
  ok('도착일도 읽는다', t.ret === '2026-04-11', String(t.ret));
  /* ⚠ 「3박 5일」은 그 자체로 모순이다(3박이면 4일). SA가 정한 대로 날짜 쪽을 쓴다. */
  ok('날짜에서 센 4박을 쓴다', t.nights === 4, String(t.nights));
  ok('제목과 어긋났다는 흔적을 남긴다', !!t.nightsConflict, JSON.stringify(t.nightsConflict));
}

/* ══ [2] 연도 뒤가 공백이어도 읽는가 ═════════════════════════════════════ */
console.log('\n[2] 「2026 06. 09 ~ 06. 13」');
{
  const t = trip(['행 사 2026 06. 09 ~ 06. 13 (3박 5일) | 예정']);
  ok('출발일을 읽는다', t.depart === '2026-06-09', String(t.depart));
  ok('도착일도 읽는다', t.ret === '2026-06-13', String(t.ret));
}
{
  /* 예전 표기가 그대로 되는지 — 넓히면서 깨지 않았는가 */
  ok('「2026.06.19 ~ 06.22」는 그대로', trip(['여행기간 2026.06.19 ~ 06.22']).depart === '2026-06-19');
  ok('「2026-03-09 ~ 2026-03-12」도 그대로', trip(['일정 2026-03-09 ~ 2026-03-12']).depart === '2026-03-09');
  ok('낱말이 없는 줄도 2차에서 읽는다(SA)', trip(['행 2026. 06. 19 ~ 06. 22 (3박 4일)']).depart === '2026-06-19');
}

/* ══ [3] 괄호를 아무거나 넘지 않는가 ═════════════════════════════════════
   ⚠ 3글자 제한이 없으면 「(자세한 내용은 아래 참조) ~」 같은 것을 건너뛰어
     문서 여기저기의 날짜 둘이 엉뚱하게 이어진다. */
console.log('\n[3] 긴 괄호는 건너뛰지 않는가');
{
  const t = trip(['비고 2026. 4. 7 (아래 표를 참고하세요) ~ 2027. 12. 31']);
  ok('긴 괄호가 낀 것은 한 기간으로 잇지 않는다', t.ret !== '2027-12-31', String(t.ret));
}

/* ══ [4] 단일 날짜를 출발일로 둔갑시키지 않는가 (SA 규칙 유지) ═══════════ */
console.log('\n[4] SA가 정한 것이 풀리지 않았는가');
{
  /* 낱말이 없는 줄의 **단일** 날짜는 2차에서 쓰지 않는다 */
  const t = trip(['수신 BSI 조서현 귀하 날짜 2026-08-06', '발신 하나이엔비티']);
  ok('작성일이 출발일로 둔갑하지 않는다', t.depart !== '2026-08-06', String(t.depart));
}
{
  /* 「N박 M일」은 박+1 또는 +2만 받는다 — 4박 6일은 야간 비행으로 실제 있다 */
  const t = trip(['일정 3박 4일']);
  ok('「3박 4일」은 그대로 받는다', t.nights === 3 && t.days === 4, JSON.stringify(t));
}

/* ⚠ 이 요약 줄의 형식은 run_all_tests.js가 정규식으로 읽는다(「결과: N pass / M fail」). */
console.log('\n결과: ' + pass + ' pass / ' + fail + ' fail');
process.exit(fail === 0 ? 0 : 1);
