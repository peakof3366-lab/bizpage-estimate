/* SC 검증 — 「입금가」(우리 1인 원가)를 판매가와 섞지 않는가

   왜 —  하나투어 원가 시트는 두 숫자를 **한 줄에 나란히** 찍는다:
       입금가 1,347,276   판매가 1,490,000   HNT 수익 50,000
     · 입금가 = 우리가 하나투어에 내는 돈 (= 우리 원가)
     · 판매가 = 하나투어가 권하는 고객가  (판매가 − 입금가 = 하나투어가 권하는 **우리** 마진)
     · HNT 수익 = 하나투어 자기 몫 (입금가 안에 이미 들어 있다)

   줄 전체에서 최댓값을 집으면 **판매가를 원가로 읽는다.** 그러면 마진이 통째로
   사라진 채 '실측'으로 굳고, 「팔면 손해인가」라는 질문에 정반대로 답하게 된다.
   코퍼스 46건 중 23건이 이 원가 시트라 파급이 크다.

   실행: node ai-loop/test_sC_deposit.js  (프로젝트 루트에서) */
const X = require('../api/_lib/pdf_extract.js');

let pass = 0, fail = 0;
const ok = (name, cond, extra = '') => {
  if (cond) { pass++; console.log('  ✓ ' + name); }
  else { fail++; console.log('  ✗ ' + name + (extra ? '  ← ' + extra : '')); }
};

let ln = 0;
const line = (cells) => {
  const out = { page: 1, y: 700 - ln * 10, idx: ln, cells: [], text: '' };
  let x = 0;
  cells.forEach((s) => { out.cells.push({ s: String(s), x }); x += 40; });
  out.text = out.cells.map((c) => c.s.trim()).filter(Boolean).join(' ');
  ln++;
  return out;
};
const doc = (rows) => { ln = 0; return rows.map((r) => line(r)); };
const dep = (rows) => X.reconcile(doc(rows), [], null).deposit;

/* ══ [1] 한 줄에 입금가·판매가가 같이 있는 양식 ═══════════════════════════ */
console.log('[1] 같은 줄의 판매가를 원가로 읽지 않는가');
{
  ok('입금가만 읽는다 (판매가 1,490,000을 집지 않는다)',
    dep([['입금가', '1,347,276', '판매가', '1,490,000']]) === 1347276,
    String(dep([['입금가', '1,347,276', '판매가', '1,490,000']])));
}
{
  ok('수익 칸이 뒤에 붙어도 입금가만 읽는다',
    dep([['입금가', '1,041,350', '판매가', '1,251,350', 'HNT 수익', '60,000']]) === 1041350,
    String(dep([['입금가', '1,041,350', '판매가', '1,251,350', 'HNT 수익', '60,000']])));
}
{
  /* 권장수익이 먼저 오는 양식 */
  ok('권장수익이 사이에 껴도 입금가만 읽는다',
    dep([['입금가', '1,007,000', '권장수익', '213,000', '판매가', '1,220,000']]) === 1007000,
    String(dep([['입금가', '1,007,000', '권장수익', '213,000', '판매가', '1,220,000']])));
}

/* ══ [2] 원가 시트가 아니면 비운다 ═══════════════════════════════════════ */
console.log('\n[2] 고객용 견적서에서 엉뚱한 값을 원가로 만들지 않는가');
{
  ok('「입금가」가 없으면 null', dep([['성인 (1인)', '1,479,125', 'x 16명', '23,666,000']]) === null,
    String(dep([['성인 (1인)', '1,479,125', 'x 16명', '23,666,000']])));
  ok('판매가만 있으면 null', dep([['판매가', '2,013,569']]) === null,
    String(dep([['판매가', '2,013,569']])));
}

/* ══ [3] 판매가(perPerson)와 원가(deposit)는 따로 나온다 ═════════════════ */
console.log('\n[3] 두 칸이 섞이지 않는가');
{
  const r = X.reconcile(doc([
    ['인원', '19'],
    ['입금가', '1,863,569', '판매가', '2,013,569'],
  ]), [], null);
  ok('원가 = 입금가', r.deposit === 1863569, String(r.deposit));
  ok('판매가 = perPerson', r.perPerson === 2013569, String(r.perPerson));
  ok('둘이 서로 다르다(같으면 마진이 사라진 것)', r.deposit !== r.perPerson);
}

/* ══ [4] ⚠ 한 문서에 입금가가 여러 개인 양식 — 실측에서 나온 함정 ════════
   출발지가 갈리면(인천/김해) 입금가 열이 두 벌이다. 지금은 **큰 쪽**을 쓴다.
   ⚠ 이건 '안전한 쪽'이라서 고른 것이지 옳다고 확인된 게 아니다 —
   큰 원가를 쓰면 「원가 아래」 판정이 더 많이 나오므로 놓치는 쪽으로 틀리지 않는다.
   어느 출발지가 기준인지는 사람이 봐야 한다. 이 성질을 여기에 고정해 둔다. */
console.log('\n[4] 입금가가 여러 개면 큰 쪽을 쓴다(놓치는 쪽으로 틀리지 않게)');
{
  ok('두 입금가 중 큰 쪽',
    dep([['입금가', '1,347,276'], ['입금가', '1,449,409']]) === 1449409,
    String(dep([['입금가', '1,347,276'], ['입금가', '1,449,409']])));
}

console.log('\n결과: ' + pass + ' pass / ' + fail + ' fail');
process.exit(fail === 0 ? 0 : 1);
