/* 목적지가 아닌데 목적지 이름을 품고 있는 말들. **먼저 지우고** 매칭한다.
   ⚠ 이걸 안 지웠다가 실제로 당했다: 「(세부내역서) 한화손해보험 뉴퍼스트 26명」이
   필리핀 **세부**로 잡혀 26명·5일 견적으로 대조됐고, 오차 -38.5%가 분포에 들어가
   중앙값을 통째로 끌어내렸다. 문서 종류를 가리키는 말이지 목적지가 아니다. */
const NOT_A_DEST = /세부\s*내역서|내역서|견적서|일정표|확정/g;

/* 요율표에 없는 목적지인데, 본문에 **이웃 목적지 이름이 함께 나오는** 것들(VC).
   본문 경로에서만 쓴다 — 파일명에 목적지가 있으면 그게 답이라 여기까지 오지 않는다.

   ⚠ **지금은 비어 있고, 그게 맞는 상태다.** 원래 여기 있던 것은 「미야코지」였다 —
     그 문서 본문에 오키나와가 나와서, 본문을 읽기 시작하면 2026-08-13에 떼어낸
     오분류가 되살아났기 때문이다. **2026-08-20에 미야코지마를 목적지로 추가하면서
     막을 이유가 사라졌다**(대표 방침: 지역이 다르면 별도로 추가한다).
     즉 **막는 것보다 나누는 것이 근본 해결**이고, 그쪽을 택했다.

   ⚠ 비워 두는 대신 **결과를 테스트가 지킨다** — test_vC [5]는 「미야코지 문서가
     오키나와로 잡히지 않는다」를 그대로 확인한다. 수단(NEAR_MISS)이 아니라 목적을
     붙들어야, 나중에 이 표를 지워도 사고가 조용히 돌아오지 않는다.
   ⚠ 다시 채워야 하는 때 — **팔지 않는 지역**인데 본문이 상위 지역명을 함께 쓰는 경우다
     (예: 이시가키·하코다테). 팔 것이면 목적지로 추가하는 쪽이 먼저다. */
const NEAR_MISS = [];

/* 본문에만 쓰는 미끼 목록(VC). 본문은 파일명보다 훨씬 시끄러워서 따로 둔다.
   ⚠ **전부 실측이다** — 코퍼스 45건 중 파일명으로 목적지를 못 정한 7건을 전수로 훑었다:

     「공동**경비**」의 **동경** → 도쿄.  7건 중 **5건**에 있다. 압도적으로 흔한 미끼다.
       ⚠ 이걸 안 지우면 「굿리치_마케팅임원 워크샵(**아오모리**)」가 **도쿄로 세어진다.**
         본문에 걸리는 것이 그것 하나뿐이라 **「여러 곳」 안전망이 안 걸린다** — 즉
         조용히 틀린 목적지로 33건 표본에 들어간다. 실제로 그 상태를 한 번 만들었고
         이 훑기가 잡았다. 미끼는 **거를 뿐 아니라 세는 것을 막는 자리**다.
     「**세부**금액」의 **세부** → 세부(Cebu). NOT_A_DEST의 「세부내역서」와 같은 유형이다.

   ⚠ 여기 없는 미끼가 새로 나오면 **대개 「여러 곳」으로 빠져 표본에서 사라진다**(안전한 쪽).
     위험한 것은 위 아오모리처럼 **미끼 하나만 걸리는** 경우다. 그래서 목적지를 못 정한
     문서가 늘면 이 훑기를 다시 돌린다 — test_vC [4]가 그 훑기를 코드로 붙들고 있다. */
const BODY_DECOY_RE = /공동\s*경비|세부\s*금액|세부\s*사항|세부\s*일정|세부\s*내용/g;

/* **요율표에 없는 지명**(VC). 「여러 곳이면 뺀다」를 실제로 작동시키는 데 필요하다.

   ⚠ 왜 필요한가 — 그 규칙은 지금까지 **요율표에 있는 이름끼리만** 셌다. 그래서
     한쪽이 요율표에 없으면 **여러 도시를 도는 일정이 한 곳으로 조용히 세어진다.**
     아오모리를 추가하자마자 드러났다: 「KS두레 VIP **아오모리,고베**」가 아오모리
     단독(-17.0%)으로 표본에 들어갔다. 그럴듯한 숫자라 눈으로는 안 걸린다.

   ⚠ **여기에 넣지 않은 두 건이 있다 — 앞선 판단이 이미 있어서다.** 훑어 보니 이 변경
     이전부터 같은 모양인 건이 둘 더 있었는데, 둘 다 「그대로 둔다」는 결정이 붙어 있다:

       (주)좋은친구_경기신용보증재단(**홍콩,심천**)     → 홍콩으로 센다
         2026-08-11 대표 지시(SU): 심천 **호텔 항목만** 평균에서 빼고
         **「같은 견적서의 항공·차량·가이드는 홍콩 것」**이다. 즉 홍콩 여행으로 본 것이다.
       EnBT-제주개발공사 **싱가포르,조호바루**        → 싱가포르로 센다
         제주도를 넣을 때 「이 건이 조용히 사라지지 않게」 일부러 고정했다(test_tE).

     둘 다 **육로로 붙어 있는 당일 이동**이고, 고베는 아오모리와 다른 지방이라
     항공·숙박 구조가 아예 다르다. 그래서 지금은 **고베만** 넣는다.
     ⚠ 이 셋을 같은 규칙으로 다룰지는 **대표 판단**이라 결정대기열에 올렸다.
       코드가 조용히 통일해 버리면 앞선 두 결정이 흔적 없이 뒤집힌다.

   ⚠ **팔기로 한 지명은 여기가 아니라 요율표로 간다**(대표 방침 2026-08-20:
     「지역이 달라지면 별도로 추가한다」). 이 목록은 「우리가 안 파는데 일정에 끼어
     있는 곳」이고, 그래서 여기 있는 이름은 **답이 아니라 거부 사유**가 된다. */
const OTHER_CITIES = ['고베'];

/* 파일 이름(없으면 본문)으로 목적지를 정한다.

   ⚠ **순서가 규칙이다.** 파일명이 먼저고, 파일명에서 **하나도 못 찾았을 때만** 본문을 본다.
     파일명이 「여러 곳」이라 답한 것은 못 찾은 게 아니라 **거부한 것**이라, 본문으로 넘겨
     한쪽을 고르면 UZ에서 고친 그 사고(대만이 푸꾸옥으로 심긴 것)가 되돌아온다.
   ⚠ 여러 목적지가 걸리면(‘대만, 푸꾸옥’) 어느 쪽 요율로 재야 할지 모른다.
     고르지 않고 뺀다 — 절반만 맞는 대조는 분포를 조용히 오염시킨다.
   ⚠ 본문은 **경유지·호텔 이름까지** 품고 있어 파일명보다 시끄럽다. 그래서 본문 경로는
     ①NEAR_MISS를 먼저 거르고 ②정확히 한 곳만 걸릴 때만 답한다.

   @param {string} name  파일 이름
   @param {string} [text] 문서 본문 — 주면 파일명이 비었을 때만 쓴다
   @returns {{key: string|null, why: string|null, from?: 'filename'|'text'}} */
function destFromName(name, text) {
  const match = (s) => DEST_ALIAS.filter(([, aliases]) => aliases.some((a) => s.includes(a)));
  /* 요율표 밖 지명이 함께 있으면 **한 곳으로 세지 않는다.** 이걸 안 보면 「여러 곳이면
     뺀다」가 요율표 안쪽에서만 작동해, 반쪽짜리 대조가 조용히 표본에 들어간다. */
  const other = (s) => OTHER_CITIES.find((c) => s.includes(c));

  const fileStr = String(name).replace(NOT_A_DEST, ' ');
  const hits = match(fileStr);
  if (hits.length === 1) {
    const o = other(fileStr);
    if (o) return { key: null, why: '목적지 여러 곳(요율표 밖: ' + o + ')' };
    return { key: hits[0][0], why: null, from: 'filename' };
  }
  if (hits.length > 1) return { key: null, why: '목적지 여러 곳' };

  if (!text) return { key: null, why: '요율표에 없는 목적지' };

  const body = String(text).replace(NOT_A_DEST, ' ').replace(BODY_DECOY_RE, ' ');
  const near = NEAR_MISS.find((n) => body.includes(n));
  if (near) return { key: null, why: '요율표에 없는 목적지(' + near + ')' };

  const inText = match(body);
  if (inText.length === 1) {
    const o = other(body);
    if (o) return { key: null, why: '목적지 여러 곳(요율표 밖: ' + o + ')' };
    return { key: inText[0][0], why: null, from: 'text' };
  }
  return { key: null, why: inText.length ? '목적지 여러 곳' : '요율표에 없는 목적지' };
}


module.exports = { DEST_ALIAS, NOT_A_DEST, NEAR_MISS, BODY_DECOY_RE, OTHER_CITIES, destFromName };
