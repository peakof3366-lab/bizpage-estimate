/* YE 검증 — 「이 견적서를 누가 발행했는가」를 재는 자가 **속지 않는가**

   왜 —  `.corpus_db.json`의 `issuer`가 45건 중 **34건을 「하나투어」**라고 하고 있었다.
   근거를 열어 보니 발행처가 아니라 대부분 **일정표의 미팅 장소**였다:

       「인천 국제공항 3층 "하나투어" 테이블에서 미팅」   ← 이 문장 하나로 14건
       「인천공항 2청사 하나투어 데스크 미팅」
       「5병은 하나투어 프로모션으로 유로라인 서비스」

   판정이 `ISSUERS.find(i => i.re.test(text))` — **본문 아무 데나 이름이 있으면 발행사**
   였기 때문이다. 반대로 진짜 발행처는 놓쳤다(`Hanatour 견적서_신선혜님(오키나와)`는
   본문이 「(주)하나이엔비티」라 「미상」이었다 — 파일 이름과 발행처가 다른 문서다).

   ⚠ 이 칸은 금액에 안 쓰인다. 그래서 더 위험했다 — 아무도 안 보는 채로 틀려 있다가
     **축으로 쓰이는 순간** 결론을 뒤집는다. 실제로 「타사 견적서가 표본에 섞였나」를
     재려고 이 칸을 집었다가 34건이 거짓인 것을 발견했다.

   ⚠ 넓히려다 **두 번 더 틀렸고 방향이 반대였다.** 그 둘을 여기서 잠근다:
     ① 「수 신: 하나투어 이선애 선임님 귀하」 — 하나투어가 **받는 쪽**이다
     ② 「HNT 수익 · 권장수익」 — 하나투어 **원가 열**이고, 같은 신호를 `basis`가 이미 센다

   → 그래서 근거를 **문서의 「발신」 칸 하나**로 좁히고, 못 정하면 미상으로 둔다.
     빈칸보다 틀린 값이 위험하다는 대표 방침 그대로다.

   실행: node ai-loop/test_yE_issuer.js  (프로젝트 루트에서) */
const fs = require('fs');
const path = require('path');
const { issuerOf } = require('./_issuer');

let pass = 0, fail = 0;
const ok = (name, cond, extra = '') => {
  if (cond) { pass++; console.log('  ✓ ' + name); }
  else { fail++; console.log('  ✗ ' + name + (extra ? '  ← ' + extra : '')); }
};

/* 합성 본문 — 실제 견적서를 쓰지 않는다(참가자 실명·거래처 단가가 들어 있다).
   문장 모양만 코퍼스에서 본뜨고 이름·숫자는 지어낸다. */

/* ══ [1] 「발신」 칸이 있으면 그것을 쓴다 ═══════════════════════════════════ */
console.log('[1] 문서가 스스로 밝힌 발신 칸');
{
  const a = issuerOf('수신 ○○대학교 김아무개 귀하 견적서 작성일 2026-01-02 발신 (주)좋은친구 출발일 2026. 1. 19.');
  ok('좋은친구로 본다', a.key === '좋은친구', a.key);
  ok('근거가 발신 칸이라고 밝힌다', /발신 칸/.test(a.why), a.why);

  const b = issuerOf('수신 ○○공사 견적서 작성일 2026-08-04 발신 (주)하나이엔비티 출발일 2026. 3. 9.');
  ok('「(주)하나이엔비티」를 EnBT로 본다 — 「하나」가 겹쳐도 하나투어로 떨어지지 않는다',
    b.key === 'EnBT', b.key);

  const c = issuerOf('수신 ○○손해보험 날짜 2026-08-04 발신 (주)하나투어 연락처 010-0000-0000');
  ok('「(주)하나투어」는 하나투어로 본다', c.key === '하나투어', c.key);
}

/* ══ [2] 미팅 장소를 발행처로 읽지 않는다 — 34건을 만든 원인 ═══════════════ */
console.log('\n[2] 일정표의 미팅 장소');
{
  const t = '1일차 06:00 인천 국제공항 제1여객터미널 3층 서편 1번 출입구 "하나투어" 테이블에서 미팅 '
          + '쓰루가이드 미팅 [피켓명 : ○○연수단] 인천 KE000 08:00 출발';
  const g = issuerOf(t);
  ok('미상으로 둔다', g.key === '미상', g.key + ' / ' + g.why);
  ok('이름이 본문에 실제로 있다 — 예전 자였다면 하나투어로 찍는다', /하나투어/.test(t));
}
{
  ok('공항 데스크 미팅도 마찬가지',
    issuerOf('1일차 인천 16:00 인천공항 2청사 하나투어 데스크 미팅 (피켓 : ○○)').key === '미상');
  ok('프로모션 언급도 마찬가지',
    issuerOf('와인 5병은 하나투어 프로모션으로 유로라인 서비스 제공').key === '미상');
}

/* ══ [3] 수신자를 발행처로 읽지 않는다 — 방향이 반대인 오판 ═══════════════ */
console.log('\n[3] 하나투어가 「받는 쪽」인 문서');
{
  /* 실측: 신한 금융플러스연도대상(발리) — 랜드사가 하나투어 앞으로 보낸 문서다 */
  const g = issuerOf('(TEL : +62 000 000) 수 신: 하나투어 이선애 선임님 귀하 Tel: 02-0000-0000 Fax:');
  ok('미상으로 둔다 — 받는 쪽은 발행처가 아니다', g.key === '미상', g.key + ' / ' + g.why);
}

/* ══ [4] 원가 열을 발행처로 읽지 않는다 — basis가 이미 세는 신호 ═════════ */
console.log('\n[4] 「HNT 수익 · 권장수익」이 든 원가 시트');
{
  const t = '대형버스 ¥ 120,000 1 1 ¥ 120,000 HNT 수익 70,000 권장수익 도로/식대/팁 등 ¥ 15,000';
  ok('미상으로 둔다', issuerOf(t).key === '미상', issuerOf(t).key);
  /* 같은 신호를 두 칸에 적지 않는다는 것이 요점이다 — 그 신호는 basis가 센다 */
  const db = fs.readFileSync(path.join(__dirname, 'build_corpus_db.js'), 'utf8');
  ok('원가 시트 판정(COST_SHEET_RE)이 그 신호를 세고 있다', /HNT\\s\*수익/.test(db));
}

/* ══ [5] 판정이 한 곳에서만 온다 (결함 생성기 ①) ═══════════════════════ */
console.log('\n[5] 발행처 판정의 단일 출처');
{
  const db = fs.readFileSync(path.join(__dirname, 'build_corpus_db.js'), 'utf8');
  ok('코퍼스 DB가 _issuer를 쓴다', /require\('\.\/_issuer'\)/.test(db));
  ok('코퍼스 DB 안에 ISSUERS 사본이 없다', !/const\s+ISSUERS\s*=/.test(db));
  const src = fs.readFileSync(path.join(__dirname, '_issuer.js'), 'utf8');
  ok('우리 법인을 하나투어보다 먼저 본다 — 순서가 판정을 바꾼다',
    src.indexOf("key: 'EnBT'") < src.indexOf("key: '하나투어'"));
}

/* ══ [6] 판정만 남기지 않는다 ═══════════════════════════════════════ */
console.log('\n[6] 근거를 함께 남기는가');
{
  const g = issuerOf('아무 회사도 없는 본문입니다');
  ok('미상일 때도 왜 미상인지 말한다', !!g.why && g.why.length > 10, g.why);
  ok('짐작하지 않는다고 밝힌다', /짐작하지 않는다/.test(g.why));
}

console.log('\n' + '─'.repeat(64));
console.log(`결과: ${pass} pass / ${fail} fail  — YE 발행처 판정`);
process.exit(fail ? 1 : 0);
