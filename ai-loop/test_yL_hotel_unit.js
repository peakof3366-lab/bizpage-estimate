/* YL 검증 — 호텔 **단가**가 문서와 앞뒤가 맞는지 보는가, 그리고 **결함이 아닌 것을
   결함이라 부르지 않는가**

   왜 —  `audit_margin_gap`(YI)이 「우리 원가 > 그쪽 판매가」인 건 3건을 이름으로 불렀다.
   있을 수 없는 값이라 뜯어보니 「글로벌 베스트 푸꾸옥(100명 5일)」에서 엔진이
   **호텔만 1인당 905,760원**을 매기고 있었다. 문서 판매가가 1,410,000원인데
   항공 380,000 + 유류 100,000만 더해도 1,385,760이라 식사·차량·마진 자리가 없다.

   원인은 **총액이 아니라 단가**였다:

       452,880 × 3 × 18 = 24,455,520      (인원은 100명인데 실 수를 18로 읽었다)

   총액 24,455,520은 맞다(1인당 244,555). 그런데 엔진은 452,880을 **1실 1박 요금**으로
   받아 `× 박수 ÷ 2인1실`로 다시 조립한다 → 905,760. 실제의 3.7배다.

   ■ 🔴 그리고 여기서 두 번째 함정을 밟을 뻔했다

   어긋난 10건을 전부 「결함」이라 부르려 했는데, **딱 절반(÷2.0)인 4건은 1인 1실
   문서**였다. 단가가 1인 1박이라 엔진의 ÷2와 정확히 어긋난다 — **사양 차이지 결함이
   아니다.** 그걸 결함이라 부르면 목록이 소음이 되고, 진짜 6건이 묻힌다.
   (WD에서 「어긋났다를 전부 결함이라 부르면 안 된다」로 두 번 겪은 그 자리다.)

   ■ 무엇이 오염되고 무엇은 안 되는가 — 이 구분이 보고의 핵심이다

   ✅ **요율 갱신은 안전하다** — 중앙값 + 표본 2건 하한이라 이상치 하나로는 안 흔들린다
      (실측: 푸꾸옥 호텔 실측중앙 214,500, 452,880이 섞여 있어도 ×1.07).
   🔴 **요율 천장·마진 비교는 건별로 그 단가를 쓴다** — 거기가 오염된다.
      금액이 아니라 **판단**이 오염되는 자리다.

   실행: node ai-loop/test_yL_hotel_unit.js  (프로젝트 루트에서) */
const fs = require('fs');
const path = require('path');

let pass = 0, fail = 0;
const ok = (name, cond, extra = '') => {
  if (cond) { pass++; console.log('  ✓ ' + name); }
  else { fail++; console.log('  ✗ ' + name + (extra ? '  ← ' + extra : '')); }
};
const HU = fs.readFileSync(path.join(__dirname, 'audit_hotel_unit.js'), 'utf8');
const MG = fs.readFileSync(path.join(__dirname, 'audit_margin_gap.js'), 'utf8');

/* ══ [1] 단가를 재는가 (총액이 아니라) ═══════════════════════════════════ */
console.log('[1] 무엇을 재는가');
{
  ok('엔진식 = 단가 × (일수−1) ÷ 2', /r\.days - 1\) \/ 2/.test(HU));
  ok('문서식 = 호텔 총액 ÷ 인원', /total \/ r\.pax/.test(HU));
  ok('총액을 의심하는 자가 아니라고 밝힌다', /총액을 의심하는 자가 아니다/.test(HU));
  ok('값을 고치지 않는다고 밝힌다', /여기서 값을 고치지 않는다/.test(HU));
}

/* ══ [2] 🔴 결함이 아닌 것을 결함이라 부르지 않는가 ═════════════════════ */
console.log('\n[2] 1인 1실을 결함이라 부르지 않는가');
{
  ok('딱 절반인 것을 따로 센다', /isSingleRoom/.test(HU));
  ok('그것을 「결함이 아니다」라고 말한다', /결함이 아니다/.test(HU));
  ok('왜 절반이 되는지 적혀 있다 (엔진이 2인1실 ÷2)', /2인 1실을 기본으로/.test(HU));
  /* ⚠ 폭을 넓히면 진짜가 그 안으로 숨는다 */
  ok('「딱 절반」의 폭이 좁다 (0.45~0.55)', /0\.45[\s\S]{0,30}0\.55/.test(HU));
  ok('넓히면 안 되는 이유가 적혀 있다', /넓히면 진짜가 그 안으로 숨는다/.test(HU));
}

/* ══ [3b] 🔴 **배수 목록을 오류라 부르지 않는가** — 내가 처음 그렇게 불렀다 ═══ */
console.log('\n[3b] 배수와 「절반 이상」의 무게를 가르는가');
{
  /* 🔴 YL 첫 판에서 「2배 넘게 어긋난 6건 = 결함」이라 보고했다. 문서를 열어 보니
     **1건만 진짜**였다. 분모가 「추출기가 고른 줄 하나」의 총액이라, 호텔 줄이 여럿인
     문서는 그 하나가 전부가 아니어서 문서식이 통째로 과소해진다.
       신한금융플러스(푸꾸옥): 본 객실 11,045,455 · 인솔자 숙박 613,636
       → **단가(204,545)는 양쪽이 같아 추출은 맞았다.** 총액만 작은 쪽이라 ×24.0.
     고른 줄에 안 흔들리는 잣대는 「엔진식 호텔 ÷ 문서 1인당」이다. 실측 6건 중
     64% 하나만 넘었고 나머지는 12~36%였다. */
  ok('배수 목록을 「확인 대상」이라 부른다', /확인 대상/.test(HU) && /오류 목록이 아니다/.test(HU));
  ok('분모가 「고른 줄 하나」라는 한계를 밝힌다', /고른 줄 하나/.test(HU));
  ok('실측 근거(본 객실 vs 인솔자 숙박)를 남겼다',
    /11,045,455/.test(HU) && /613,636/.test(HU));
  ok('「1인당의 절반 이상」을 진짜 잣대라 부른다', /진짜 잣대/.test(HU));
  ok('그 잣대가 고른 줄에 안 흔들린다고 밝힌다', /고른 줄에 안 흔들린다/.test(HU));
  ok('6건 중 1건만 진짜였다는 실측을 남겼다', /6건 중 진짜는 1건/.test(HU));
}

/* ══ [3] 무엇이 오염되고 무엇은 아닌지 가르는가 ═════════════════════════ */
console.log('\n[3] 요율은 안전하고 판단이 오염된다는 구분');
{
  ok('요율 갱신은 중앙값·표본 하한으로 안전하다고 말한다',
    /중앙값/.test(HU) && /표본 2건 하한/.test(HU));
  ok('천장·마진 비교는 건별로 그 단가를 쓴다고 경고한다',
    /요율 천장/.test(HU) && /건별로/.test(HU));
  ok('실측 근거(푸꾸옥 214,500 · ×1.07)를 남겼다', /214,500/.test(HU) && /1\.07/.test(HU));
}

/* ══ [4] 마진 도구가 「원가 > 판매가」를 이름으로 부르는가 ══════════════ */
console.log('\n[4] 있을 수 없는 값을 이름으로 부르는가');
{
  ok('부대비용을 원가에서 갈라 본다', /baseNoAnc/.test(MG));
  ok('두 보기를 나란히 찍는다', /부대비용을 원가로 봄/.test(MG) && /부대비용을 뺌/.test(MG));
  ok('두 보기의 결론이 갈리면 그렇다고 말한다', /두 보기의 결론이 다르다/.test(MG));
  ok('빼고도 남는 건을 이름으로 부른다', /우리 원가 > 그쪽 판매가/.test(MG));
  ok('그것이 마진 문제가 아니라고 못박는다', /마진 문제가 아니다/.test(MG));
}

/* ══ [5] 실제로 걸리는가 — 이 자가 무딘 자는 아닌가 (결함 생성기 ③) ═════ */
console.log('\n[5] 일부러 망가뜨려 본다');
{
  /* 도구는 파일을 즉시 실행하므로 규칙만 여기서 최소로 재현해 **가르는지**만 본다.
     ⚠ 판정은 도구가 한다 — 여기는 「무딘 자가 아니다」를 보이는 자리다. */
  const ratio = (unit, days, total, pax) => (unit * (days - 1) / 2) / (total / pax);
  /* 실측: 글로벌 베스트 푸꾸옥 — 100명 5일, 452,880, 총액 24,455,520 */
  const r1 = ratio(452880, 5, 24455520, 100);
  ok('실 수를 잘못 읽은 건이 2배를 넘는다', r1 >= 2, '×' + r1.toFixed(1));
  /* 실측: 고은회 제주도 — 24명 3일, 90,000, 총액 4,320,000 (1인 1실) */
  const r2 = ratio(90000, 3, 4320000, 24);
  ok('1인 1실 건은 딱 절반이다', r2 >= 0.45 && r2 <= 0.55, '÷' + (1 / r2).toFixed(1));
  /* 정상: 2인 1실이고 박수도 맞으면 1에 가깝다 */
  const r3 = ratio(200000, 5, 200000 * 4 * 50, 100);
  ok('정상인 건은 1 근처라 안 걸린다', r3 > 0.5 && r3 < 2, '×' + r3.toFixed(2));
}

console.log('\n' + '─'.repeat(64));
console.log(`결과: ${pass} pass / ${fail} fail  — YL 호텔 단가 정합성`);
process.exit(fail ? 1 : 0);
