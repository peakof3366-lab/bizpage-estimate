/* 표본이 이만큼 늘면 다시 재라고 말한다 */
const 늘어남문턱 = 0.20;
/* 민감한 결론(표본이 작아 잘 뒤집히는 것)은 더 일찍 말한다 */
const 민감문턱 = 0.10;

function 판정(c, 지금) {
  if (지금 == null || !c.그때) return { 상태: '모름', 배수: null };
  const 늘어난비율 = (지금 - c.그때) / c.그때;
  const 문턱 = c.민감 ? 민감문턱 : 늘어남문턱;
  if (지금 < c.그때) return { 상태: '줄었다', 늘어난비율 };
  return { 상태: 늘어난비율 >= 문턱 ? '다시재기' : '유효', 늘어난비율, 문턱 };
}

async function run() {
  const rows = (await loadCorpus({ useCache: true, quiet: true })).filter((r) => !r.error);
  const 지금 = {};
  for (const [k, v] of Object.entries(표본종류)) 지금[k] = v.세기(rows);

  console.log('\n══ 서 있는 결론이 아직 유효한가 ══');
  console.log('지금 표본: ' + Object.entries(표본종류)
    .map(([k, v]) => v.이름 + ' ' + 지금[k] + '건').join(' · '));
  console.log('─'.repeat(78));

  const 재야할것 = [], 유효 = [];
  for (const c of 결론들) {
    const p = 판정(c, 지금[c.표본]);
    (p.상태 === '다시재기' ? 재야할것 : 유효).push({ c, p });
  }

  if (재야할것.length) {
    console.log('\n🔴 다시 재야 합니다 — ' + 재야할것.length + '건');
    console.log('   (표본이 늘었습니다. 지금 결론은 **그때 표본에서** 내린 것입니다)');
    재야할것.forEach(({ c, p }) => {
      console.log('\n   [' + c.커밋 + '] ' + c.한줄);
      console.log('      표본 ' + 표본종류[c.표본].이름 + ' ' + c.그때 + '건 → 지금 ' + 지금[c.표본] + '건'
        + '  (+' + Math.round(p.늘어난비율 * 100) + '%' + (c.민감 ? ' · 잘 뒤집히는 결론' : '') + ')');
      console.log('      다시: ' + c.다시);
    });
  }

  if (유효.length) {
    console.log('\n✓ 아직 그때 표본 그대로 — ' + 유효.length + '건');
    유효.forEach(({ c, p }) => {
      const 지금값 = 지금[c.표본];
      console.log('   [' + c.커밋 + '] ' + 표본종류[c.표본].이름 + ' ' + c.그때 + '건'
        + (지금값 === c.그때 ? ' (그대로)' : ' → ' + 지금값 + '건 (+' + Math.round((p.늘어난비율 || 0) * 100) + '%)')
        + '  — ' + c.한줄.slice(0, 44) + '…');
    });
  }

  console.log('\n' + '─'.repeat(78));
  if (!재야할것.length) {
    console.log('✅ 지금 다시 잴 것은 없습니다.');
    console.log('   ⚠ 「결론이 맞다」는 뜻이 아니라 **「그때와 같은 표본이다」**는 뜻입니다.');
  } else {
    console.log('⚠ 다시 재기 전까지 위 결론을 근거로 쓰지 마십시오 — 표본이 달라졌습니다.');
  }
  console.log('⚠ 근거와 과정은 **커밋 메시지**에 있습니다(여기엔 안 옮겨 적습니다).');
  console.log('⚠ 새 결론을 내렸으면 이 파일의 `결론들`에 한 줄 넣으십시오 —');
  console.log('   안 넣으면 그 결론도 표본이 늘 때 조용히 낡습니다.\n');
}

module.exports = { 결론들, 표본종류, 판정, 늘어남문턱, 민감문턱 };
if (require.main === module) run().catch((e) => { console.error(e); process.exit(1); });
