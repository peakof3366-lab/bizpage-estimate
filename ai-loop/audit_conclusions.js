/* ═══════════════════════════════════════════════════════════════════════════
   서 있는 결론이 **아직 유효한가** (YU) — 표본이 늘면 다시 재야 하는 것들
   ───────────────────────────────────────────────────────────────────────────
   🔴 왜 필요한가. 이 저장소에는 「측정으로 내린 결론」이 여럿 서 있다 —
   「요율을 더 다듬어도 정확해지지 않는다」·「골프 축은 우연이다」·「우리 마진은 얇지 않다」.
   전부 **그때의 표본에서** 내린 것이다. 그런데 대표 방침은 **견적서가 계속 는다**이다.

   표본이 늘면 이 결론들은 뒤집힐 수 있다. 그런데 지금은 **아무것도 그 사실을 말해
   주지 않는다.** 숫자만 기억에 남고 근거 표본 수는 사라져서, 다음 사람(또는 다음
   세션의 나)이 **낡은 결론을 사실로 들고 간다.**
   실제로 메모리에 「`28/36`만 옮겨 적지 말 것」·「폭 12.0%만 옮겨 적지 말 것」이라는
   경고가 여러 번 적혀 있다 — 그게 이미 일어나고 있다는 뜻이다.

   ■ 여기 담는 것과 담지 않는 것
     담는다:   그 결론을 **언제·어느 표본 몇 건에서** 내렸나 · **다시 재는 명령**
     안 담는다: 결론의 근거와 과정. 그건 **커밋 메시지**에 있다(이 저장소의 기록 방식).
   ⚠ 근거를 여기 옮겨 적으면 커밋과 두 벌이 되고 반드시 어긋난다(결함 생성기 ①).
     그래서 한 줄 요약 + 커밋 이름만 둔다.

   ■ 언제 「다시 재라」고 하는가
   표본이 **20% 이상** 늘면 말한다. 한두 건에 매번 말하면 그 줄을 안 읽게 되고,
   두 배가 될 때까지 기다리면 그동안 틀린 결론으로 일하게 된다.
   ⚠ **막지 않는다. 말만 한다.** 다시 재는 것은 사람이 판단할 일이다.

   실행: node ai-loop/audit_conclusions.js
   ⚠ 읽기 전용이다.
   ═══════════════════════════════════════════════════════════════════════════ */
const path = require('path');
const { loadCorpus } = require('./_corpus_cache.js');

/* 표본의 종류 — 결론마다 「무엇이 늘어야 다시 재는가」가 다르다.
   ⚠ 전체 문서가 늘어도 역검증 표본은 안 늘 수 있다(정답지가 없으면 안 들어온다).
     그래서 종류를 갈라 센다 — 「45건이 됐으니 전부 다시 재라」는 틀린 말이다. */
const 표본종류 = {
  전체: { 이름: '코퍼스 문서', 세기: (rows) => rows.length },
  정답지: { 이름: '1인당을 읽은 문서', 세기: (rows) => rows.filter((r) => r.perPerson).length },
  역검증: {
    이름: '역검증에 들어가는 문서',
    /* 정답지 + 출발일 + 목적지가 다 있어야 오차를 잴 수 있다 */
    세기: (rows) => rows.filter((r) => r.perPerson && r.dates && r.dates.departDate && r.dest && r.dest.key).length,
  },
  골프: {
    이름: '역검증 표본 안의 골프 일정',
    세기: (rows) => rows.filter((r) => r.perPerson && r.dates && r.dates.departDate && r.dest && r.dest.key
      && r.golf && r.golf.isGolfTrip).length,
  },
};

