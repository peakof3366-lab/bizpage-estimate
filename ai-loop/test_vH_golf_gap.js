/* VH 검증: **엔진이 담을 칸이 아예 없는 항목** — 골프.

   왜 —
   표본 작업을 이어가다 나온 것이다. 코퍼스 45건을 훑어 보니:

       골프가 든 일정          **13건**
       요율에 골프 요금이 있는 곳  **4곳뿐** (제주도 · 오키나와 · 후아힌 · 카자흐스탄)

   다낭 · 푸꾸옥 · 발리 · 하노이는 골프 견적서가 표본에 들어 있는데 **요율에 골프 칸이 없다.**
   골프 요금이 0이면 엔진은 그 줄을 **아예 만들지 않으므로**(getGolfFee가 0이면 화면이 잠근다)
   그 견적서는 구조적으로 싸게 나온다 — **요율이 틀려서가 아니다.**
   실측: 다낭 뉴퍼스트가 -41.9%로 표본 최악이고, 그 문서에 골프가 10번 나온다.

   ⚠ 그리고 그 비용이 문서에서는 **차량·관광 칸에 섞여** 들어가 칸별 실측 중앙값까지
     끌어올린다 — 다낭 차량이 요율의 2.84배(🔴)로 찍힌 것이 그 모양이다.
     즉 이 격차를 요율 문제로 읽고 차량 단가를 올리면 **엉뚱한 칸을 올리는 것**이 된다.

   ⚠ **골프 금액을 문서에서 뽑을 수는 없었다.** 전수로 열어 봤다 —
     「캐디팁」·「골프조 게임비」는 라벨만 있고 숫자가 없고, 하노이·푸꾸옥은
     「선택 일정 [관광/자유/골프]」라 아예 금액이 없다. 추출기가 못 뽑은 게 아니라
     **문서에 없다.** 그래서 골프 요금을 넣는 것은 실거래가라 대표 판단이다.

   여기서 고정하는 것:
   ① 요율에 골프 요금이 있는 곳과 없는 곳이 실제로 갈린다(짐작이 아니라 값으로).
   ② 모르는 목적지는 **비운다** — 짐작값이 그대로 고객 견적에 나간다(GOLF_FEES 규칙).
   ③ 오차 축에 「골프 일정」이 있고, **못 잴 때는 몇 건이 모자란지 말한다.**

   실행: node ai-loop/test_vH_golf_gap.js  (프로젝트 루트에서) */
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const AI = path.join(ROOT, 'ai-loop');
const DATA = require(path.join(ROOT, 'data.js'));

let pass = 0, fail = 0;
const ok = (name, cond, extra = '') => {
  if (cond) { pass++; console.log('  ✓ ' + name); }
  else { fail++; console.log('  ✗ ' + name + (extra ? '  → ' + extra : '')); }
};

console.log('\n[1] 골프 요금이 있는 곳과 없는 곳이 값으로 갈린다');
{
  /* 이 넷은 **실측**이다 — 견적서에서 뽑은 값이라 추정 배지가 아니라 실측 배지가 맞다 */
  ['제주도', '오키나와', '후아힌', '카자흐스탄'].forEach((k) => {
    ok('① ' + k + ' 는 골프 요금이 있다', DATA.getGolfFee(k) > 0, String(DATA.getGolfFee(k)));
  });
  /* ⚠ 이 넷이 지금 표본을 흔드는 곳이다 — 골프 견적서는 있는데 요율에 칸이 없다 */
  ['다낭', '푸꾸옥', '발리', '하노이'].forEach((k) => {
    ok('① ' + k + ' 는 아직 골프 요금이 없다 (표본이 흔들리는 곳)', DATA.getGolfFee(k) === 0,
      String(DATA.getGolfFee(k)));
  });
}

console.log('\n[2] 모르는 목적지는 비운다 — 짐작값을 만들지 않는다');
{
  ok('② 요율표에 없는 목적지는 0이다', DATA.getGolfFee('없는곳') === 0);
  /* ⚠ 미야코지마는 2026-08-20에 새로 넣은 목적지다. 오키나와를 복사한 출발점이지만
     **골프 요금은 일부러 안 가져왔다** — 섬이 골프로 유명해도 실측이 없다.
     여기가 0이 아니면 누군가 이웃 값을 복사한 것이고, 그 숫자가 고객 견적에 나간다. */
  ok('② 미야코지마에 오키나와 골프 요금을 복사해 오지 않았다', DATA.getGolfFee('미야코지마') === 0,
    String(DATA.getGolfFee('미야코지마')));
  ok('② 아오모리도 마찬가지다', DATA.getGolfFee('아오모리') === 0);

  /* 요율 행의 값이 GOLF_FEES보다 우선한다 — 담당자가 요율 관리에서 고치면 그게 이긴다 */
  const jeju = DATA.find((d) => d.destination_key === '제주도');
  ok('② 요율 행을 먼저 본다 (담당자가 고친 값이 이긴다)',
    DATA.getGolfFee('제주도') === (typeof jeju.golf_fee === 'number' ? jeju.golf_fee : DATA.GOLF_FEES['제주도']));
}

console.log('\n[3] 오차 축이 골프를 본다 — 그리고 못 잴 때 몇 건인지 말한다');
{
  const s = fs.readFileSync(path.join(AI, 'audit_error_axes.js'), 'utf8');
  ok('③ 「골프 일정」 축이 있다', /key: '골프 일정'/.test(s));
  ok('③ 요율에 골프 요금이 있는지로 가른다', /golfFee/.test(s) && /getGolfFee/.test(s));
  /* ⚠ 언급 몇 번부터 골프 일정으로 볼지 — 1회는 지나가는 말이다(실측: 미야코지마·한화GA) */
  ok('③ 지나가는 언급 한 번은 골프 일정으로 안 본다', /length >= 3/.test(s));
  /* ⚠ 「못 잰다」만 찍으면 영영 안 될 일인지 한두 장이면 될 일인지 알 수 없다.
     실제로 골프 축은 양쪽 3건씩이라 **각각 한 장씩이면 재기 시작한다.** */
  ok('③ 못 잴 때 무리별 건수를 찍는다', /지금: /.test(s) && /아직 못 잰다/.test(s));
}

console.log('\n결과: ' + pass + ' pass / ' + fail + ' fail');
process.exit(fail ? 1 : 0);
