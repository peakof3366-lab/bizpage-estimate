/* UH 검증 — 표본을 늘린 두 가지가 **늘린 만큼 잘못 읽지 않는가**

   이번에 넓힌 것 둘:
     ① 「총 여행경비」·「1인 여행경비」도 총계·1인당이다 (굿리치 가고시마·아오모리 양식)
     ② 일정표의 **요일이 연도를 증명한다** (「4/4(토)」는 2026, 「04/04/Fri」는 2025)

   왜 조심해야 하나 —
     ①은 「여행 경비」라는 말이 **맺음말에도** 있다. 코퍼스 46건 중 9건이
        「※ 여행 경비 중 과세 항목은 '알선 수수료'이며」를 달고 있다. 그 줄을 총계로 읽으면
        엉뚱한 숫자가 총계가 되고, 총계는 「뽑은 줄 합계 ≤ 총계」 검산의 기준이라
        **읽은 값 전체의 신뢰도가 무너진다.**
     ②는 날짜다. 출발일 하나가 시즌 계수와 리드타임 계수를 **둘 다** 정한다.
        요일로 해를 고르는 것은 짐작을 줄이는 장치이지 늘리는 장치가 아니어야 한다 —
        그래서 **맞는 해가 없으면 비우는지**를 여기서 직접 잰다.

   실행: node ai-loop/test_uH_labels_and_dow.js  (프로젝트 루트에서) */
const X = require('../api/_lib/pdf_extract.js');

let pass = 0, fail = 0;
const ok = (name, cond, extra = '') => {
  if (cond) { pass++; console.log('  ✓ ' + name); }
  else { fail++; console.log('  ✗ ' + name + (extra ? '  → ' + extra : '')); }
};

let ln = 0;
const at = (texts) => {
  const o = { page: 1, y: 700 - ln * 10, idx: ln, cells: texts.map((s, i) => ({ s, x: 60 + i * 70 })), text: texts.join(' ') };
  ln++;
  return o;
};
/* 금액 줄이 없으면 readOneBlock이 일찍 빠지므로 최소한의 표를 함께 둔다 */
const table = () => [
  at(['1일 중식', '30,000', '1', '14', '420,000']),
  at(['1일 석식', '40,000', '1', '14', '560,000']),
];
const datesOf = (lines) => X.readOneBlock(lines, {}, null).dates;

/* ══ ① 「총/1인 여행경비」 ═════════════════════════════════════════════════
   실측(굿리치 가고시마) — 이 두 줄을 못 읽어 그 견적서가 역검증에서 통째로 빠져 있었다.
     총 여행경비  14   26,619,180
     1인 여행경비      1,901,370          (1,901,370 × 14 = 26,619,180으로 맞는다) */
console.log('[1] 「총 여행경비」·「1인 여행경비」를 읽는가');
{
  ln = 0;
  const r = X.readOneBlock([
    at(['인 원', '14']),
    at(['총 여행경비', '14', '26,619,180']),
    at(['1인 여행경비', '1,901,370']),
  ].concat(table()), {}, null);
  ok('총계를 읽는다', r.grandTotal === 26619180, String(r.grandTotal));
  ok('1인당을 읽는다', r.perPerson === 1901370, String(r.perPerson));
}

/* ⚠ 🔴 **여기가 이 넓힘의 위험한 쪽이다.** 「여행 경비」만 보면 맺음말 9건이 걸린다. */
console.log('\n[2] 맺음말의 「여행 경비」를 총계로 읽지 않는가');
{
  ln = 0;
  const r = X.readOneBlock([
    at(['인 원', '14']),
    at(['※ 여행 경비 중 과세 항목은 \'알선 수수료\'이며, 부가세 1,200,000 원이 포함되어 있습니다']),
  ].concat(table()), {}, null);
  ok('**「총」·「1인」이 안 붙은 「여행 경비」는 총계가 아니다**', !r.grandTotal, String(r.grandTotal));
  ok('1인당으로도 읽지 않는다', !r.perPerson, String(r.perPerson));
}
{
  /* 여행일자·여행인원 안내문도 흔하다(코퍼스 4건) — 여기에도 금액이 붙어 있으면 안 걸려야 한다 */
  ln = 0;
  const r = X.readOneBlock([
    at(['인 원', '14']),
    at(['여행일자, 여행인원, 세부일정 등에 따라 여행경비는 변동될 수 있음 (기준 1,500,000)']),
  ].concat(table()), {}, null);
  ok('「여행경비는 변동될 수 있음」 안내문도 안 읽는다', !r.grandTotal, String(r.grandTotal));
}

/* ══ ② 요일이 연도를 증명한다 ════════════════════════════════════════════ */
console.log('\n[3] 문서에 연도가 둘이면 요일이 가르는가');
{
  /* 실측(굿리치 체코): 「2025 …연도대상」과 「2026 굿리치 RM 연도대상」이 둘 다 있어
     예전 규칙(연도가 딱 하나일 때만)이 깨져 **출발일이 통째로 비어 있었다.**
     4/4은 2025년 금요일 · 2026년 토요일 → 문서의 「(토)」가 2026을 고른다. */
  ln = 0;
  const d = datesOf([
    at(['[2025 굿리치 RM총괄수석부문 연도대상] 미팅장소 집결']),
    at(['1. 2026 굿리치 RM 연도대상(체코&오스트리아)']),
    at(['4/4(토)']),
  ].concat(table()));
  ok('요일이 맞는 해를 고른다 (2025 아님)', d.departDate === '2026-04-04', String(d.departDate));
}

console.log('\n[4] 「견적 뒤에 여행 간다」 규칙보다 요일이 앞서는가');
{
  /* 실측(굿리치 바르셀로나): 작성일 2026-08-06은 실은 **PDF로 뽑은 날**이었다.
     그런데 「견적보다 앞선 날짜면 이듬해」 규칙이 2027-04-04를 만들어 냈다.
     문서는 「04/04/Fri」라고 적혀 있고, 4/4이 금요일인 해는 2025다. */
  ln = 0;
  const d = datesOf([
    at(['2호차 확정 일정표 DATE : 2026-08-06']),
    at(['04/04/Fri']),
  ].concat(table()));
  ok('작성일에서 유도한 2027이 아니라 요일이 맞는 2025를 고른다',
    d.departDate === '2025-04-04', String(d.departDate));
  ok('작성일은 그대로 남는다', d.quoteDate === '2026-08-06', String(d.quoteDate));
}

/* ⚠ 🔴 **여기가 이 넓힘의 위험한 쪽이다.** 후보 연도 중 요일이 맞는 것이 없으면
   그건 우리가 연도를 모른다는 뜻이지, 아무 해나 써도 된다는 뜻이 아니다. */
console.log('\n[5] 요일이 맞는 해가 없으면 비우는가');
{
  ln = 0;
  const d = datesOf([
    at(['2026 사내 연수 계획']),
    at(['4/4(수)']),           /* 2026-04-04는 토요일이다 — 문서가 스스로 어긋난다 */
  ].concat(table()));
  ok('**문서가 반증한 연도는 쓰지 않는다**', !d.departDate, String(d.departDate));
}
{
  /* 연도가 아예 없으면 고를 후보 자체가 없다 */
  ln = 0;
  const d = datesOf([at(['4/4(토)'])].concat(table()));
  ok('문서에 연도가 없으면 비운다', !d.departDate, String(d.departDate));
}

/* ══ 회귀 — 요일이 없는 표기는 예전 규칙 그대로여야 한다 ═══════════════════ */
console.log('\n[6] 요일 없는 표기는 예전 규칙 그대로인가 (회귀 없음)');
{
  ln = 0;
  const d = datesOf([
    at(['견적 작성일 2026-01-05']),
    at(['02월 04일']),
    at(['02월 05일']),
  ].concat(table()));
  ok('작성일의 해를 그대로 쓴다', d.departDate === '2026-02-04', String(d.departDate));
}
{
  /* 작성일보다 앞선 날이면 이듬해 — 요일이 없을 때는 이 규칙이 그대로 살아 있어야 한다 */
  ln = 0;
  const d = datesOf([
    at(['견적 작성일 2026-11-20']),
    at(['02월 04일']),
  ].concat(table()));
  ok('작성일보다 앞서면 이듬해로 본다', d.departDate === '2027-02-04', String(d.departDate));
}
{
  /* 연도가 딱 하나면 요일이 없어도 그것을 쓴다 (예전 경로) */
  ln = 0;
  const d = datesOf([
    at(['2026년 상반기 워크샵 계획']),
    at(['02월 04일']),
  ].concat(table()));
  ok('연도가 하나뿐이면 그것을 쓴다', d.departDate === '2026-02-04', String(d.departDate));
}

/* ⚠ 이 요약 줄의 형식은 run_all_tests.js가 정규식으로 읽는다(「결과: N pass / M fail」). */
console.log('\n결과: ' + pass + ' pass / ' + fail + ' fail');
process.exit(fail === 0 ? 0 : 1);
