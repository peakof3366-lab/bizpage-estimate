/* 요율표가 가진 칸 — 이 밖의 돈은 엔진이 낼 수 없다(부대비용으로만 담긴다) */
const RATE_ITEM_KEYS = ['airfare', 'fuel', 'hotel', 'meal', 'vehicle', 'guide', 'sight'];

/* 코퍼스에서 세는 칸 — 골프까지 여덟. 「우리 칸으로 담을 수 있는 돈」을 잴 때 쓴다. */
const CORPUS_ITEM_KEYS = [...RATE_ITEM_KEYS, 'golf'];

/* 환율로 되돌릴 수 있는 값 (SG) */
const FX_FIELD_KEYS = [...RATE_ITEM_KEYS, 'sell'];

/* 담당자가 칸별로 확정할 수 있는 값 (SW) */
const MANUAL_FIELD_KEYS = [...RATE_ITEM_KEYS, 'golf', 'sell'];

module.exports = { RATE_ITEM_KEYS, CORPUS_ITEM_KEYS, FX_FIELD_KEYS, MANUAL_FIELD_KEYS };
